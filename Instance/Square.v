(** ** Two invariants, independent of the classification

    Everything above rests on [wsq_classify].  A count that rests on a
    single lemma is a count that says nothing if that lemma is silently
    weakened, so this section adds two invariants that are proved from
    the path structure alone and never mention it.  They are the shape
    of [Construction/Free/Quiver/Examples.v]'s [chain_e10_length]: a
    numerical quantity attached to each arrow, which a change to the
    PRESENTATION or to the closure machinery would have to violate
    loudly.  Not a collapse of this category — see the precision note
    below, which is deliberately stronger than this sentence.

    THEY ARE COMPLEMENTARY, and neither subsumes the other.  RANK rules
    out five of the seven empty hom-sets, by arithmetic on the endpoints
    alone; it cannot see the other two (B and C have the same rank —
    [wsq_rank_cannot_decide_BC] records exactly where the argument
    stops), and it cannot separate the two diagonals, both being
    two-step, which is why [free_square_diagonals_neq] discriminates on
    the INTERMEDIATE NODE instead.  LENGTH is invariant under the
    imposed congruence ([square_length_invariant]), so the quotient
    merged only equal-length paths.

    BE PRECISE ABOUT WHAT THE LENGTH INVARIANT BUYS HERE, because it is
    easy to overstate.  Its contrapositive [square_no_collapse] has NO
    instance in this category, and that is a fact about the square
    rather than a defect: by [square_hom_length] every arrow between a
    given pair of nodes already has the same length, namely the rank
    difference, so there is no parallel pair of differing lengths for it
    to separate.  What the invariant is for is that it is proved from
    the congruence closure ALONE — by induction on [CongClosure], using
    neither [wsq_classify] nor [Square_Thin] nor the count — so it fails
    loudly if the presentation is ever changed to relate paths of
    different lengths, or if the closure machinery stops being sound.
    That is the guard [Construction/Free/Quiver/Examples.v]'s
    [chain_e10_length] provides for the free case, carried across the
    quotient. *)

(** *** Rank: every edge raises it by exactly one *)

Definition wsq_rank (x : SquareNode) : nat :=
  match x with Sq_A => 0 | Sq_B => 1 | Sq_C => 1 | Sq_D => 2 end.

Lemma wsq_edge_rank {x y : SquareNode} (e : SquareEdge x y) :
  wsq_rank y = S (wsq_rank x).
Proof. destruct e; reflexivity. Qed.

(** Hence a path's length is exactly the rank it climbs.  The rank is
    written FIRST in the sum on purpose: at concrete endpoints the sum
    then reduces to a numeral applied to [S], so each corollary below
    closes by [discriminate] with no arithmetic decision procedure. *)
Lemma wsq_path_rank (x y : SquareNode) (p : x ~{FreeSquare}~> y) :
  wsq_rank y = (wsq_rank x + tlist_length p)%nat.
Proof.
  induction p as [ | i j e p IH ]; simpl.
  - now rewrite PeanoNat.Nat.add_0_r.
  - rewrite IH, (wsq_edge_rank e); simpl.
    now rewrite PeanoNat.Nat.add_succ_r.
Qed.

(** Five of the seven empty hom-sets, re-derived by arithmetic alone. *)
Corollary wsq_rank_no_path_BA (p : Sq_B ~{FreeSquare}~> Sq_A) : False.
Proof. pose proof (wsq_path_rank _ _ p) as H; discriminate H. Qed.

Corollary wsq_rank_no_path_CA (p : Sq_C ~{FreeSquare}~> Sq_A) : False.
Proof. pose proof (wsq_path_rank _ _ p) as H; discriminate H. Qed.

Corollary wsq_rank_no_path_DA (p : Sq_D ~{FreeSquare}~> Sq_A) : False.
Proof. pose proof (wsq_path_rank _ _ p) as H; discriminate H. Qed.

Corollary wsq_rank_no_path_DB (p : Sq_D ~{FreeSquare}~> Sq_B) : False.
Proof. pose proof (wsq_path_rank _ _ p) as H; discriminate H. Qed.

Corollary wsq_rank_no_path_DC (p : Sq_D ~{FreeSquare}~> Sq_C) : False.
Proof. pose proof (wsq_path_rank _ _ p) as H; discriminate H. Qed.

(** The two rank cannot decide: [Sq_B] and [Sq_C] have the same rank, so
    the argument above degenerates to [tlist_length p = 0] and stops.
    They are supplied by the classification instead, and are stated here
    only to record that the rank route is INCOMPLETE — the two proofs
    below are [wsq_classify]'s, not rank's. *)
Corollary wsq_rank_cannot_decide_BC (p : Sq_B ~{FreeSquare}~> Sq_C) :
  tlist_length p = 0%nat.
Proof.
  pose proof (wsq_path_rank _ _ p) as H; simpl in H.
  now injection H.
Qed.

(** Every arrow between a given pair of nodes climbs exactly the rank
    difference, so all of them have the SAME length.  Stated at
    [Square], where it holds because the quotient does not change the
    hom types. *)
Theorem square_hom_length (x y : SquareNode) (p : x ~{Square}~> y) :
  (wsq_rank x + tlist_length p)%nat = wsq_rank y.
Proof. symmetry; exact (wsq_path_rank x y p). Qed.

(** *** Length: invariant under the imposed congruence *)

(** Equivalent paths of the free category have equal length —
    [tlist'_equiv_lengths] ([Construction/Free/Quiver.v]) at this
    quiver. *)
Lemma wsq_equiv_length {x y : SquareNode} (p q : x ~{FreeSquare}~> y) :
  p ≈ q → tlist_length p = tlist_length q.
Proof. intro H; exact (tlist'_equiv_lengths _ _ _ _ _ _ _ H). Qed.

(** The single imposed equation relates two paths of the SAME length —
    both diagonals are two-step — which is what makes length survive the
    quotient. *)
Lemma wsq_relation_length {x y : SquareNode}
  (p q : x ~{FreeSquare}~> y) (Hr : fe_rel SquareEqns x y p q) :
  tlist_length p = tlist_length q.
Proof.
  destruct Hr as [i [Hp Hq]].
  destruct x, y; simpl in i; try solve [ exact (Fin.case0 _ i) ].
  simpl in Hp, Hq.
  rewrite (wsq_equiv_length _ _ Hp), (wsq_equiv_length _ _ Hq).
  reflexivity.
Qed.

(** Composition in a free category is path concatenation, so its length
    is the sum.  Stated over an arbitrary quiver, which is what makes it
    match the congruence closure's [cc_comp] goal — there the ambient
    category prints as [FreeOnQuiver (fp_quiver SquarePresentation)]
    rather than through this file's [FreeSquare] abbreviation. *)
Lemma wsq_comp_length {G : Quiver} {x y z : FreeOnQuiver G}
  (f : y ~> z) (g : x ~> y) :
  tlist_length (f ∘ g) = (tlist_length g + tlist_length f)%nat.
Proof. exact (tlist_app_length g f). Qed.

(** So [Square] is GRADED by path length: equivalent arrows have equal
    length.  It is proved by induction on the congruence closure itself,
    using none of [wsq_classify], [Square_Thin] or the count — that
    independence is the point.  It is NOT a statement a collapse of this
    category would break: by [square_hom_length] every parallel pair
    already has equal length, so the conclusion holds unconditionally
    here and any identification of parallel arrows satisfies it.  What
    it guards is the PRESENTATION and the closure machinery; see the
    precision note in the section header. *)
Theorem square_length_invariant {x y : SquareNode} (p q : x ~{Square}~> y) :
  p ≈ q → tlist_length p = tlist_length q.
Proof.
  intro H.
  induction H as [ x y p q Hr | x y p q He | x y p q _ IH
                 | x y p q r _ IH1 _ IH2 | x y z f f' g g' _ IH1 _ IH2 ].
  - exact (wsq_relation_length p q Hr).
  - exact (wsq_equiv_length p q He).
  - now symmetry.
  - now transitivity (tlist_length q).
  - rewrite !wsq_comp_length.
    now rewrite IH1, IH2.
Qed.

(** The contrapositive, which is the form a reader wants: arrows of
    different length are never identified. *)
Corollary square_no_collapse {x y : SquareNode} (p q : x ~{Square}~> y) :
  (tlist_length p = tlist_length q → False) → p ≈ q → False.
Proof. intros Hne H; exact (Hne (square_length_invariant p q H)). Qed.

(** *** The diagonal is a composite, measured

    Each generator is a one-step path and the diagonal a two-step one,
