(** * The walking commutative square, by generators and relations

    nLab: https://ncatlab.org/nlab/show/commutative+square
    nLab: https://ncatlab.org/nlab/show/free+category
    Book: Mac Lane, Categories for the Working Mathematician, 2nd ed.,
          §II.8, printed p. 52 (Exercise 1: describe the category
          generated by the square diagram subject to commutativity, and
          count its arrows)
    Book: Riehl, Category Theory in Context, Dover 2016, §1.6,
          Example 1.6.6 (printed p. 41: the commutative square as the
          shape 2 × 2) and Example 1.6.9 (printed p. 42: the shape
          2 × 3 and commutative rectangles)
    Book: Fong and Spivak, Seven Sketches in Compositionality, CUP 2019,
          §3.2.2 (finite presentations of categories)

    Mac Lane's exercise names a diagram — four objects, four arrows
    arranged in a square — and asks for the category it generates once
    the square is required to commute.  The answer he wants is a count:
    nine arrows, four of them identities.  The fifth non-identity arrow
    is the diagonal, and the whole point of the exercise is that it is
    NOT a fifth generator: it is the common value of the two composites,
    and the single imposed relation is exactly what makes those two
    composites one arrow rather than two.

    This file builds that category as a finite presentation over
    [Construction/Free/Quiver/Presented.v], proves the count, and
    records the shape's universal property: a functor out of it is a
    commutative square in the target, and nothing else.

    WHAT IS DELIVERED HERE.  (1) the presentation [SquarePresentation]
    and the category [Square], with the relation holding
    ([square_commutes]) and the diagonal identified as the common
    composite ([square_diagonal_via_B], [square_diagonal_via_C]);
    (2) a classification of every PATH of the underlying free category
    by its endpoints, at LEIBNIZ strength ([wsq_classify] — the free
    hom-sets are enumerated on the nose, not merely up to [≈]), from
    which everything else follows; (3) thinness of [Square]
    ([Square_Thin]), the absence of nontrivial endomorphisms
    ([square_endo_id]) and emptiness of the seven hom-sets that carry no
    arrow ([square_no_hom_BA] and its six siblings); (4) the arrow count,
    both as a duplicate-free enumeration of the nine inhabited endpoint
    pairs with soundness and completeness, and as a number folded over
    all sixteen pairs ([square_arrow_total] = 9,
    [square_identity_total] = 4,
    [square_nonidentity_total] = 5); (5) the same count for the FREE
    square ([free_square_arrow_total] = 10), so the quotient is measured
    to merge exactly one pair and nothing else; (6) the index-shape
    reading, [Square ⟶ C] against [CommutingSquare C] with both round
    trips and the universal property; (7) the identification of a
    commutative square with a MORPHISM of the arrow category
    ([Construction/Arrow.v]), in both directions.

    Checkbox A of the issue — the identification with 2 × 2 — is
    [Instance/Square/Product.v]; checkbox B — the shape 2 × 3 and
    commutative rectangles — is [Instance/Square/Rectangle.v].

    WHY THE COUNT IS THE SUBSTANTIAL HALF, and how it is kept honest.
    An arrow count in a presented category is a statement about
    [≈]-classes, and a quotient can always collapse further than
    intended; a count proved by collapse would be worthless.  Four
    separate facts keep this one from being vacuous.  First, the free
    count is proved TOO: [free_square_arrow_total] = 10 against
    [square_arrow_total] = 9, so exactly one identification happened.
    Second, that identification is exhibited on both sides — the two
    diagonals are provably DISTINCT in the free category
    ([free_square_diagonals_distinct], already in
    [Construction/Free/Quiver/Presented.v]) and provably EQUAL in the
    presented one ([square_relation_holds]).  Third, the diagonal is
    proved to be a composite and not a generator: the quiver has exactly
    four edges ([square_generator_total] = 4, computed from the
    [FiniteQuiver] data), while the presented category has five
    non-identity arrows.  Fourth, and independently of the
    classification the other three route through, the shape carries two
    numerical invariants: a RANK that re-derives five of the seven empty
    hom-sets by arithmetic alone, and a path LENGTH that is invariant
    under the imposed congruence ([square_length_invariant], proved by
    induction on [CongClosure] and using neither [wsq_classify] nor
    [Square_Thin]), so that the diagonal is a two-step path at EVERY
    representative ([square_diagonal_is_two_steps]) while every
    generator is one step.  That paragraph's own limits are stated where
    the invariants are proved.

    THE CLASSIFICATION IS AT LEIBNIZ STRENGTH, deliberately.  The edges
    of [SquareQuiver] carry the standard [eq] setoid
    ([Build_Quiver_Standard_Eq]), so [wsq_classify] can and does
    conclude a Leibniz equality of paths rather than a [tlist]
    equivalence — every path from A to D IS [square_diag_fh] or IS
    [square_diag_gk], on the nose.  That is stronger than the [≈]-level
    statement and it is what makes the free count a count of ARROWS
    rather than of classes.  Only the presented statements descend to
    [≈], because only there is [≈] coarser than [=].

    TWO SQUARE SHAPES ALREADY EXIST IN THE TREE, and the reader should
    not confuse them with this one or with each other.
    [Construction/Free/Quiver/Presented.v] declares [SquareQuiver] over
    [SquareNode]/[SquareEdge] with the four edges NAMED [Sq_f], [Sq_g],
    [Sq_h], [Sq_k]; that is the quiver this file presents, reused rather
    than redeclared, along with its [square_diag_fh]/[square_diag_gk]
    and the negative result [free_square_diagonals_distinct] that file
    already proves.  [Theory/Diagram.v] declares a DIFFERENT quiver
    under the SAME name [SquareQuiver], over [SqNode] with anonymous
    unit-valued edges, serving the diagram-commutativity development
    there ([square_commutative_iff], [sq_len_rank]).  The two names
    collide, harmlessly, because no file imports both; this one imports
    the [Construction/] quiver and not [Theory/Diagram.v].  That file's
    [sq_paths] is the independent shadow of [wsq_classify] one level
    down: it classifies the DENOTATIONS of paths in a target category
    under a commutativity hypothesis, whereas [wsq_classify] classifies
    the paths themselves, in the free category, with no hypothesis and
    at Leibniz equality.  Its [sq_len_rank] rank argument is the other
    standard route to the same classification, and is NOT the route
    taken here — the induction below is direct, and the seven empty
    hom-sets fall out of it rather than out of a rank inequality.
    Finally, [Construction/Sq.v] is unrelated: it is the double category
    of commuting squares in an ambient category.

    A UNIVERSE PIN IN THE DONOR WAS LIFTED to make this file's clause
