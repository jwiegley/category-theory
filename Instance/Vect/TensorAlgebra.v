Next Obligation. lam2_1. Qed.

Definition lam2_scal_proper
  : Proper (@equiv _ (is_setoid Z_setoid_object)
              ==> @equiv _ (is_setoid lam2_setoid_object)) lam2_scal :=
  fun r s H => f_equal (fun z : Z => ((z, 0, 0, 0) : lam2)%Z) H.

Definition lam2_scal_morphism
  : SetoidMorphism (is_setoid Z_setoid_object) (is_setoid lam2_setoid_object) :=
  {| morphism := lam2_scal; proper_morphism := lam2_scal_proper |}.

Lemma lam2_scal_add (a b : Z) :
  lam2_scal (a + b)%Z = lam2_add (lam2_scal a) (lam2_scal b).
Proof. unfold lam2_scal, lam2_add; apply lam2_eq4; ring. Qed.

Lemma lam2_scal_mul (a b : Z) :
  lam2_scal (a * b)%Z = lam2_mul (lam2_scal a) (lam2_scal b).
Proof. unfold lam2_scal, lam2_mul; apply lam2_eq4; ring. Qed.

Program Definition lam2_scalar : Int_Ring ~{Rng}~> Lam2 := {|
  rig_map := lam2_scal_morphism
|}.
Next Obligation. reflexivity. Qed.
Next Obligation. intros a b; exact (lam2_scal_add a b). Qed.
Next Obligation. reflexivity. Qed.
Next Obligation. intros a b; exact (lam2_scal_mul a b). Qed.

Lemma lam2_scalar_central : ∀ (k : Z) (a : lam2),
  rig_mul Lam2 (rig_map lam2_scalar k) a
    ≈ rig_mul Lam2 a (rig_map lam2_scalar k).
Proof. intros k [ [ [ s x ] y ] p ]; lam2_crunch. Qed.

Definition Lam2_AAlg : AAlgObject Int_CRng :=
