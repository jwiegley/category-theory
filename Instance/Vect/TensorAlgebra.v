  alin_map := {| morphism := tt_gen |}
|}.
Next Obligation. intros v w H; exact (te_gen H). Qed.
Next Obligation. intros v w; exact (te_gen_add v w). Qed.
Next Obligation. intros r v; exact (te_gen_smul_l r v). Qed.

(** * Evaluation: the universal property in element form *)

Section TensorEvaluation.

Context (A : AAlgObject K).
Context (f : AAlgLinear V A).

Notation AR := (aalg_ring A).

Fixpoint teval (t : TTerm) : carrier (rig_setoid AR) :=
  match t with
  | tt_scal a  => rig_map (aalg_unit A) a
  | tt_gen v   => alin_map f v
  | tt_add s t => rig_add AR (teval s) (teval t)
  | tt_neg s   => ring_neg AR (teval s)
  | tt_mul s t => rig_mul AR (teval s) (teval t)
  end.

(** Twenty cases, one per constructor of [tt_eq].  Five are congruence for
    a former, the first two saturating under the source setoids; seven are
    ring laws of A, four of those additionally spending a preservation law
    of the structure map, because the zero and the one of T(V) are scalars
    rather than formers of their own; two are the structure map's
    preservation of sums and of products; three are the linear map's own
    laws, of which the right-hand linearity clause is the one that spends
    CENTRALITY of the structure map's image; and the last two are the
    target setoid's symmetry and transitivity. *)
Lemma teval_respects (s t : TTerm) : tt_eq s t → teval s ≈ teval t.
Proof.
  intro He.
  induction He as
    [ a b Hab
    | v w Hvw
    | s s' t t' _ IHs _ IHt
    | s s' _ IHs
    | s s' t t' _ IHs _ IHt
    | s t w | s t | s | s
    | s t w | s | s
    | s t w | s t w
    | a b | a b
    | v w | r v | r v
    | s t _ IHst
    | s t w _ IHst _ IHtw ]; simpl.
  - exact (proper_morphism (rig_map (aalg_unit A)) _ _ Hab).
  - exact (proper_morphism (alin_map f) _ _ Hvw).
  - exact (rig_add_respects AR _ _ IHs _ _ IHt).
  - exact (ring_neg_respects AR _ _ IHs).
  - exact (rig_mul_respects AR _ _ IHs _ _ IHt).
  - exact (rig_add_assoc AR _ _ _).
  - exact (rig_add_comm AR _ _).
  - rewrite (rig_map_zero (aalg_unit A)); apply rig_add_zero_l.
  - rewrite (rig_map_zero (aalg_unit A)); apply (ring_neg_l AR).
  - exact (rig_mul_assoc AR _ _ _).
  - rewrite (rig_map_one (aalg_unit A)); apply rig_mul_one_l.
  - rewrite (rig_map_one (aalg_unit A)); apply rig_mul_one_r.
  - exact (rig_distr_l AR _ _ _).
  - exact (rig_distr_r AR _ _ _).
  - exact (rig_map_add (aalg_unit A) a b).
  - exact (rig_map_mul (aalg_unit A) a b).
  - exact (alin_add f v w).
  - exact (alin_smul f r v).
  - rewrite (alin_smul f r v); apply aalg_central.
  - exact (symmetry IHst).
  - exact (transitivity IHst IHtw).
Qed.

(** *** The extension

    STRENGTH, MEASURED.  Preservation of ADDITION and of MULTIPLICATION
    close by [reflexivity] — those are clauses of the fixpoint.
    Preservation of ZERO and of ONE does NOT: the zero of T(V) is
    [tt_scal (rig_zero K)], so the fold returns the structure map's value
    there, and reaching the target's zero is that map's own preservation
    law.  Only respectfulness has content beyond that. *)
Program Definition tensor_extend_ring : TensorRing ~{Rng}~> AR := {|
  rig_map := {| morphism := teval |}
|}.
Next Obligation. intros s t He; exact (teval_respects s t He). Qed.
Next Obligation. simpl; exact (rig_map_zero (aalg_unit A)). Qed.
Next Obligation. intros s t; simpl; reflexivity. Qed.
Next Obligation. simpl; exact (rig_map_one (aalg_unit A)). Qed.
Next Obligation. intros s t; simpl; reflexivity. Qed.

Lemma tensor_extend_triangle :
  aalg_unit A ≈ tensor_extend_ring ∘ aalg_unit TensorAlg.
Proof. intro a; simpl; reflexivity. Qed.

Definition tensor_extend : TensorAlg ~{AAlg K}~> A :=
  (tensor_extend_ring; tensor_extend_triangle).

(** The extension restricts to [f] on generators and to the structure map
    on scalars, both DEFINITIONALLY — the fixpoint's first two clauses are
    those two equations.  This is the convertibility exception: the
    equations are between elements of A's carrier, not between
    morphisms. *)
Example tensor_extend_gen (v : carrier (cmon_setoid V)) :
  rig_map (`1 tensor_extend) (tt_gen v) = alin_map f v := eq_refl.

Example tensor_extend_scal (a : carrier (rig_setoid (`1 K))) :
  rig_map (`1 tensor_extend) (tt_scal a) = rig_map (aalg_unit A) a := eq_refl.

(** *** Uniqueness

    Any ring homomorphism out of T(V) agreeing with [f] on generators and
    with the structure map on scalars IS the evaluation.  The induction has
    one case per former: the two base cases are the hypotheses, and the
    other three are homomorphism laws of the competitor — preservation of
    sums, of negation (Theory/Algebra/Rig.v's [RigHom_neg], a theorem
    rather than a field) and of products. *)
Lemma tensor_extend_unique (g : TensorRing ~{Rng}~> AR)
  (Hscal : ∀ a, rig_map g (tt_scal a) ≈ rig_map (aalg_unit A) a)
  (Hgen : ∀ v, rig_map g (tt_gen v) ≈ alin_map f v) (t : TTerm) :
  rig_map g t ≈ teval t.
Proof.
  induction t as [ a | v | s IHs t IHt | s IHs | s IHs t IHt ]; simpl.
  - exact (Hscal a).
  - exact (Hgen v).
  - rewrite (rig_map_add g s t); exact (rig_add_respects AR _ _ IHs _ _ IHt).
  - rewrite (RigHom_neg TensorRing AR g s).
    exact (ring_neg_respects AR _ _ IHs).
  - rewrite (rig_map_mul g s t); exact (rig_mul_respects AR _ _ IHs _ _ IHt).
Qed.

End TensorEvaluation.

(* A morphism of algebras out of T(V) automatically agrees with the
   structure map on scalars: that is exactly its triangle. *)
Lemma tensor_alg_hom_scal (A : AAlgObject K) (g : TensorAlg ~{AAlg K}~> A)
  (a : carrier (rig_setoid (`1 K))) :
  rig_map (`1 g) (tt_scal a) ≈ rig_map (aalg_unit A) a.
Proof. symmetry; exact (`2 g a). Qed.

(** * The exterior algebra

    Λ(V) is T(V) with the single further generating equation v·v ≈ 0 for
    generators v.  The relation [et_eq] therefore has SEVEN constructors
    rather than twenty: the first embeds the whole of [tt_eq], so every
    ring law and every linearity clause is inherited rather than restated,
    and the remaining six are the new equation, congruence for the three
    formers it can appear under, and the two closure rules. *)

Inductive et_eq : TTerm → TTerm → Type :=
  | ee_base {s t} : tt_eq s t → et_eq s t

  (* the alternating relation, at GENERATORS only *)
  | ee_alt v : et_eq (tt_mul (tt_gen v) (tt_gen v))
                     (tt_scal (rig_zero (`1 K)))

  | ee_add {s s' t t'} :
      et_eq s s' → et_eq t t' → et_eq (tt_add s t) (tt_add s' t')
  | ee_neg {s s'} : et_eq s s' → et_eq (tt_neg s) (tt_neg s')
  | ee_mul {s s' t t'} :
      et_eq s s' → et_eq t t' → et_eq (tt_mul s t) (tt_mul s' t')

  | ee_sym {s t} : et_eq s t → et_eq t s
  | ee_trans {s t u} : et_eq s t → et_eq t u → et_eq s u.

Lemma et_refl (s : TTerm) : et_eq s s.
Proof. exact (ee_base (tt_refl s)). Qed.

Lemma et_eq_Equivalence : Equivalence et_eq.
Proof.
  constructor.
  - exact et_refl.
  - exact (fun s t => ee_sym).
  - exact (fun s t u => ee_trans).
Qed.

Definition et_Setoid : Setoid TTerm := {|
  equiv        := et_eq;
  setoid_equiv := et_eq_Equivalence
|}.

(** Every law is [ee_base] of the corresponding law of T(V): the ring
    structure is inherited wholesale, which is the formal content of "Λ(V)
    is a quotient of T(V)". *)

Definition ExtRig : RigObject := {|
  rig_setoid := {| carrier := TTerm; is_setoid := et_Setoid |};
  rig_zero := TZ;
  rig_add := tt_add;
  rig_one := TO;
  rig_mul := tt_mul;
  rig_add_respects := fun _ _ Hs _ _ Ht => ee_add Hs Ht;
  rig_mul_respects := fun _ _ Hs _ _ Ht => ee_mul Hs Ht;
  rig_add_assoc := fun s t u => ee_base (te_add_assoc s t u);
  rig_add_comm := fun s t => ee_base (te_add_comm s t);
  rig_add_zero_l := fun s => ee_base (te_add_zero_l s);
  rig_mul_assoc := fun s t u => ee_base (te_mul_assoc s t u);
  rig_mul_one_l := fun s => ee_base (te_mul_one_l s);
  rig_mul_one_r := fun s => ee_base (te_mul_one_r s);
  rig_distr_l := fun s t u => ee_base (te_distr_l s t u);
  rig_distr_r := fun s t u => ee_base (te_distr_r s t u);
  rig_mul_zero_l := fun s => ee_base (te_mul_zero_l s);
  rig_mul_zero_r := fun s => ee_base (te_mul_zero_r s)
|}.

Definition ExtRing : RingObject := {|
  ring_rig := ExtRig;
  ring_neg := tt_neg;
  ring_neg_respects := fun _ _ Hs => ee_neg Hs;
  ring_neg_l := fun s => ee_base (te_add_neg_l s)
|}.

