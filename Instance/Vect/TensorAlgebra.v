Section TensorUniversal.

Context (K : CRng).

(** The universal mapping property, in the shape [universal_arrow_from_UMP]
    consumes: the insertion, read as a morphism of K-modules into the
    underlying module of T(V), factors every module map into the underlying
    module of an algebra. *)
Lemma tensor_universal (V : RMod (`1 K)) (A : AAlg K)
  (h : V ~{RMod (`1 K)}~> fobj[AAlg_Forget_Mod K] A) :
  ∃! g : TensorAlg V ~{AAlg K}~> A,
    h ≈ fmap[AAlg_Forget_Mod K] g ∘ module_hom_of_aalg_linear (tensor_insert V).
Proof.
  unshelve eexists.
  - exact (tensor_extend A (aalg_linear_of_module_hom h)).
  - intro v; simpl; reflexivity.
  - intros g Hg t; simpl.
    symmetry.
    apply (tensor_extend_unique A (aalg_linear_of_module_hom h) (`1 g)).
    + intro a; exact (tensor_alg_hom_scal A g a).
    + intro v; symmetry; exact (Hg v).
Qed.

Definition tensor_universal_arrow (V : RMod (`1 K))
  : UniversalArrow V (AAlg_Forget_Mod K) :=
  universal_arrow_from_UMP V (AAlg_Forget_Mod K) (TensorAlg V)
    (module_hom_of_aalg_linear (tensor_insert V)) (tensor_universal V).

(* The same content in the direct encoding, where the universal object is
   named rather than projected out of a comma category. *)
Program Definition tensor_auniversal_arrow (V : RMod (`1 K))
  : AUniversalArrow V (AAlg_Forget_Mod K) (TensorAlg V) := {|
  universal_arrow := module_hom_of_aalg_linear (tensor_insert V)
|}.
Next Obligation.
  intros V A h.
  unshelve eexists.
  - exact (tensor_extend A (aalg_linear_of_module_hom h)).
  - intro v; simpl; reflexivity.
  - intros g Hg t; simpl.
    symmetry.
    apply (tensor_extend_unique A (aalg_linear_of_module_hom h) (`1 g)).
    + intro a; exact (tensor_alg_hom_scal A g a).
    + intro v; exact (Hg v).
Qed.

(** Mac Lane §IV.2 Exercise 1, in the part this issue delivers: the tensor
    algebra is the left adjoint of the functor that forgets an associative
    K-algebra down to its underlying K-module.  Both come out of the
    generic machinery with no further proof. *)
Definition TensorFunctor : RMod (`1 K) ⟶ AAlg K :=
  LeftAdjointFunctorFromUniversalArrows (AAlg_Forget_Mod K)
    tensor_universal_arrow.

Definition tensor_adjunction : TensorFunctor ⊣ AAlg_Forget_Mod K :=
  AdjunctionFromUniversalArrows (AAlg_Forget_Mod K) tensor_universal_arrow.

(** The free functor's object part IS the term algebra, and the universal
    arrow IS the insertion: [universal_arrow_from_UMP] stores the supplied
    morphism as the second projection of the comma object it builds, so no
    proof is involved. *)
Example TensorFunctor_obj (V : RMod (`1 K)) :
  fobj[TensorFunctor] V = TensorAlg V := eq_refl.

Example tensor_arrow_is_insert (V : RMod (`1 K)) :
  @arrow _ _ V (AAlg_Forget_Mod K) (tensor_universal_arrow V)
    = module_hom_of_aalg_linear (tensor_insert V) := eq_refl.

(** The unit of the adjunction is the generator insertion, on the nose:
    [unit] is DERIVED in Theory/Adjunction.v as the transpose of the
    identity, so what it computes to has to be checked. *)
Definition tensor_unit (V : RMod (`1 K))
  : V ~{RMod (`1 K)}~> fobj[AAlg_Forget_Mod K] (fobj[TensorFunctor] V) :=
  @Category.Theory.Adjunction.unit _ _ _ _ tensor_adjunction V.

Example tensor_unit_is_gen (V : RMod (`1 K)) (v : carrier (cmon_setoid V)) :
  cmon_map (rm_hom (tensor_unit V)) v = tt_gen v := eq_refl.

End TensorUniversal.

(** * Non-degeneracy

    Nothing below is obtained by induction on [tt_eq] or [et_eq]: an
    induction on a quotienting relation cannot produce a negative
    statement.  Every separation is obtained by mapping OUT of the term
    algebra into a concrete algebra where the two candidates have visibly
    different values, which is the only route a presentation by generators
    and relations offers — the same route Instance/Rng/Polynomial.v takes
    for [poly_x_not_constant] and Instance/Mod/Tensor.v for its own
    negative results. *)

(** ** The tensor algebra is genuinely non-commutative

    The witness module is the underlying ℤ-module of
    Instance/Rng/Algebras/Associative.v's upper-triangular matrix algebra,
    and the witness linear map is [alin_id], the identity.  So the
    extension sends a generator [tt_gen x] to x itself, and two generators
    whose matrices do not commute give two products of generators that
    cannot be identified in T(V).  This is the fact that made [AAlg]
    necessary: over [KAlg] this T(V) does not exist. *)

Definition UT2_Mod : RModObject (`1 Int_CRng) := AAlg_RMod UT2_AAlg.

Definition tensor_to_UT2
  : @TensorAlg Int_CRng UT2_Mod ~{AAlg Int_CRng}~> UT2_AAlg :=
  tensor_extend UT2_AAlg (alin_id UT2_AAlg).

(* The extension computes on generators and on products of them. *)
Example tensor_to_UT2_gen (x : ut2) :
  rig_map (`1 tensor_to_UT2) (@tt_gen Int_CRng UT2_Mod x) = x := eq_refl.

Example tensor_to_UT2_e11_e12 :
  rig_map (`1 tensor_to_UT2) (tt_mul (@tt_gen Int_CRng UT2_Mod ut2_e11) (@tt_gen Int_CRng UT2_Mod ut2_e12))
    = ut2_e12 := eq_refl.

Example tensor_to_UT2_e12_e11 :
  rig_map (`1 tensor_to_UT2) (tt_mul (@tt_gen Int_CRng UT2_Mod ut2_e12) (@tt_gen Int_CRng UT2_Mod ut2_e11))
    = ut2_zero := eq_refl.

Theorem tensor_not_commutative :
  tt_eq (tt_mul (@tt_gen Int_CRng UT2_Mod ut2_e11) (@tt_gen Int_CRng UT2_Mod ut2_e12))
        (tt_mul (@tt_gen Int_CRng UT2_Mod ut2_e12) (@tt_gen Int_CRng UT2_Mod ut2_e11)) → False.
Proof.
  intro H.
  apply UT2_not_commutative.
  exact (proper_morphism (rig_map (`1 tensor_to_UT2)) _ _ H).
Qed.

(* A generator is not a scalar: the module used is not the zero module,
   which is the degeneracy the header names. *)
Theorem tensor_gen_not_scalar (r : Z) :
  tt_eq (@tt_gen Int_CRng UT2_Mod ut2_e12) (@tt_scal Int_CRng UT2_Mod r) → False.
Proof.
  intro H.
  pose proof (proper_morphism (rig_map (`1 tensor_to_UT2)) _ _ H) as H2.
  unfold ut2_eqT, ut2_e12, ut2_scal in H2.
  inversion H2.
Qed.

(* ...and the base ring is not the trivial ring: 1 ≉ 0 already in T(V). *)
Theorem tensor_nontrivial :
  tt_eq (@tt_scal Int_CRng UT2_Mod 1%Z) (@tt_scal Int_CRng UT2_Mod 0%Z)
    → False.
Proof.
  intro H.
  pose proof (proper_morphism (rig_map (`1 tensor_to_UT2)) _ _ H) as H2.
  unfold ut2_eqT, ut2_scal in H2.
  inversion H2.
Qed.

(** ** A four-dimensional algebra, to separate v∧w from w∧v

    The classical description of the exterior algebra of a rank-two free
    module over ℤ, written out by hand: the quadruple (s, a, b, p) stands
    for s + a·e₁ + b·e₂ + p·e₁∧e₂, and the product is the one the
    relations e₁∧e₁ = e₂∧e₂ = 0 and e₁∧e₂ = −e₂∧e₁ dictate.  It is written
    out rather than obtained from [ExtAlg] because its purpose is to be a
    TARGET: separations are proved by mapping OUT of a term algebra into
    something whose elements can be told apart by computation, and
    [ExtAlg] of anything has no normal form, so nothing could be told
    apart inside it.  NO isomorphism between [Lam2] and any [ExtAlg] is
    proved or claimed; all that is used below is that [Lam2] is an object
    of [AAlg Int_CRng] — the scalars are central because ℤ is
    commutative — and that a suitable alternating map lands in it. *)

Definition lam2 : Type := (Z * Z * Z * Z)%type.

Definition lam2_eqT (x y : lam2) : Type := x = y.

Lemma lam2_eqT_Equivalence : Equivalence lam2_eqT.
Proof.
  constructor; unfold lam2_eqT.
  - intro x; reflexivity.
  - intros x y H; now symmetry.
  - intros x y z H1 H2; now transitivity y.
Qed.

Definition lam2_setoid_object : SetoidObject := {|
  carrier := lam2;
  is_setoid := {| equiv := lam2_eqT; setoid_equiv := lam2_eqT_Equivalence |}
|}.

Definition lam2_zero : lam2 := (0, 0, 0, 0)%Z.
Definition lam2_one : lam2 := (1, 0, 0, 0)%Z.

Definition lam2_add (x y : lam2) : lam2 :=
  match x, y with
  | (s, a, b, p), (s', a', b', p') =>
      ((s + s')%Z, (a + a')%Z, (b + b')%Z, (p + p')%Z)
  end.

Definition lam2_neg (x : lam2) : lam2 :=
  match x with (s, a, b, p) => ((- s)%Z, (- a)%Z, (- b)%Z, (- p)%Z) end.

Definition lam2_mul (x y : lam2) : lam2 :=
  match x, y with
  | (s, a, b, p), (s', a', b', p') =>
      ((s * s')%Z, (s * a' + a * s')%Z, (s * b' + b * s')%Z,
       (s * p' + a * b' - b * a' + p * s')%Z)
  end.

Definition lam2_scal (r : Z) : lam2 := (r, 0, 0, 0)%Z.

Lemma lam2_eq4 (s a b p s' a' b' p' : Z) :
  s = s' → a = a' → b = b' → p = p' →
  ((s, a, b, p) : lam2) = (s', a', b', p').
Proof. intros H1 H2 H3 H4; now subst. Qed.

Ltac lam2_crunch :=
  cbv beta iota delta
    [lam2_eqT lam2_add lam2_neg lam2_mul lam2_zero lam2_one lam2_scal];
  apply lam2_eq4; ring.

Ltac lam2_1 := intros [ [ [ ? ? ] ? ] ? ]; lam2_crunch.
Ltac lam2_2 := intros [ [ [ ? ? ] ? ] ? ] [ [ [ ? ? ] ? ] ? ]; lam2_crunch.
Ltac lam2_3 := intros [ [ [ ? ? ] ? ] ? ] [ [ [ ? ? ] ? ] ? ] [ [ [ ? ? ] ? ] ? ]; lam2_crunch.

Lemma lam2_add_respects : Proper (lam2_eqT ==> lam2_eqT ==> lam2_eqT) lam2_add.
Proof. intros x y Hxy z w Hzw; unfold lam2_eqT in *; now subst. Qed.

Lemma lam2_mul_respects : Proper (lam2_eqT ==> lam2_eqT ==> lam2_eqT) lam2_mul.
Proof. intros x y Hxy z w Hzw; unfold lam2_eqT in *; now subst. Qed.

Lemma lam2_neg_respects : Proper (lam2_eqT ==> lam2_eqT) lam2_neg.
Proof. intros x y Hxy; unfold lam2_eqT in *; now subst. Qed.

Program Definition Lam2_Rig : RigObject := {|
  rig_setoid := lam2_setoid_object;
  rig_zero := lam2_zero;
  rig_add := lam2_add;
