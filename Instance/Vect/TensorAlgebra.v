(** ** Λ(V) does not collapse

    The witness module is the underlying ℤ-module of [Lam2], and the
    witness alternating map is the projection onto the degree-one part —
    linear because the module structure is componentwise, and alternating
    because the square of a degree-one element is (ab − ba) in the top
    slot, which is zero. *)

Definition Lam2_Mod : RModObject (`1 Int_CRng) := AAlg_RMod Lam2_AAlg.

Definition lam2_deg1 (x : lam2) : lam2 :=
  match x with (_, a, b, _) => (0, a, b, 0)%Z end.

Definition lam2_deg1_proper
  : Proper (@equiv _ (is_setoid lam2_setoid_object)
              ==> @equiv _ (is_setoid lam2_setoid_object)) lam2_deg1 :=
  fun x y H => f_equal lam2_deg1 H.

Program Definition lam2_deg1_lin : AAlgLinear Lam2_Mod Lam2_AAlg := {|
  alin_map := {| morphism := lam2_deg1; proper_morphism := lam2_deg1_proper |}
|}.
Next Obligation.
  intros [ [ [ s a ] b ] p ] [ [ [ s' a' ] b' ] p' ].
  cbv beta iota delta [lam2_eqT lam2_add lam2_deg1]; apply lam2_eq4; ring.
Qed.
Next Obligation.
  intros r [ [ [ s a ] b ] p ].
  cbv beta iota delta [lam2_eqT lam2_mul lam2_scal lam2_deg1]; simpl.
  apply lam2_eq4; ring.
Qed.

Program Definition lam2_deg1_alt : AltLinear Lam2_Mod Lam2_AAlg := {|
  alt_lin := lam2_deg1_lin
|}.
Next Obligation.
  intros [ [ [ s a ] b ] p ].
  cbv beta iota delta [lam2_eqT lam2_mul lam2_zero lam2_deg1]; simpl.
