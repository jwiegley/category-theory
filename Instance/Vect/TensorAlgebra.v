(** The defining relation, in the vocabulary of the algebra. *)
Lemma ext_alt (v : carrier (cmon_setoid V)) :
  rig_mul ExtRing (tt_gen v) (tt_gen v) ≈ rig_zero ExtRing.
Proof. exact (ee_alt v). Qed.

