  {| alt_lin := ext_insert_lin; alt_sq := ext_alt |}.

(** ANTISYMMETRY IS DERIVED, not assumed: expanding
    (v + w)∧(v + w) ≈ 0 and cancelling the two square terms leaves
    v∧w + w∧v ≈ 0.  The converse — recovering v∧v ≈ 0 from antisymmetry —
    is not proved and is not claimed; see the header for what is and is
    not established about the two forms. *)
Lemma ext_anticomm (v w : carrier (cmon_setoid V)) :
  rig_mul ExtRing (tt_gen v) (tt_gen w)
    ≈ ring_neg ExtRing (rig_mul ExtRing (tt_gen w) (tt_gen v)).
Proof.
  apply (ab_neg_unique (ring_ab ExtRing)); simpl.
  assert (Hsum : @equiv _ (is_setoid (rig_setoid ExtRing))
                   (tt_gen (cmon_plus V v w))
                   (rig_add ExtRing (tt_gen v) (tt_gen w)))
    by exact (ee_base (te_gen_add v w)).
  pose proof (ee_alt (cmon_plus V v w)) as H.
  change (@equiv _ (is_setoid (rig_setoid ExtRing))
            (rig_mul ExtRing (tt_gen (cmon_plus V v w))
                             (tt_gen (cmon_plus V v w)))
            (rig_zero ExtRing)) in H.
  rewrite Hsum in H.
  rewrite rig_distr_r, !rig_distr_l in H.
  rewrite (ext_alt v), (ext_alt w) in H.
  rewrite rig_add_zero_l, rig_add_zero_r in H.
  exact H.
Qed.

