(** * CRing is reflective in Ring: the commutator-ideal quotient

    Riehl, "Category Theory in Context", §4.6, Example 4.6.13 (ii),
    printed p. 170 (PDF p. 190), read from the page image, catalog item
    riehl:4.6:example13, the second half of the clause: after the
    abelianization of groups, "A similar construction defines a left
    adjoint to the inclusion CRing ↪ Ring of commutative rings into the
    category of all rings."  The box this file answers asks for "The
    reflector Ring ⟶ CRing, quotienting by the commutator ideal -- the
    two-sided ideal generated by xy − yx -- with the quotient map as
    unit, exhibiting CRing as a full reflective subcategory of Ring."
    Mac Lane, "Categories for the Working Mathematician", 2nd ed.,
    §IV.3, printed p. 92 (PDF p. 101), read from the page image, gives
    the group case this imitates: "Ab is reflective in Grp.  For, if
    G/[G, G] is the usual factor-commutator group of a group G, then
    hom(G/[G, G], A) ≅ hom(G, A) for A abelian, and Ab is full in Grp."
    nLab: https://ncatlab.org/nlab/show/reflective+subcategory

    BACKGROUND.  Riehl states the ring case in one sentence, as the
    analogue of abelianization, and neither Riehl nor Mac Lane spells
    out the construction.  The quotient is by the smallest two-sided
    ideal containing every commutator xy − yx: any ring map into a
    commutative ring sends each commutator to zero, hence kills that
    ideal, hence factors through the quotient, and the quotient is
    commutative because the class of xy − yx is zero.  That is the whole
    argument, and it is the one formalized below; the group case is
    Instance/Grp/Abelianize/Reflective.v.

