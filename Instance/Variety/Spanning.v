(** * Spanning arrows for a variety: Mac Lane's Remark 1 *)

(* nLab: https://ncatlab.org/nlab/show/subobject
   nLab: https://ncatlab.org/nlab/show/solution+set+condition
   nLab: https://ncatlab.org/nlab/show/variety+of+algebras

   Mac Lane, "Categories for the Working Mathematician", 2nd ed. (GTM 5),
   §V.7 ("Subobjects and Generators"), book pp. 127-128 (PDF pp. 136-137).
   Definition 6 calls an arrow f : x → G a SPANNING when it factors
   through no proper subobject of a; Lemma 2 says that when every family
   of subobjects of A has an intersection and G preserves those
   intersections, every arrow factors through a spanning one, so the
   spanning arrows out of x form a solution set; Remark 1 is the
   application Mac Lane cares about -- for the underlying-set functor of
   a variety the spanning factorization is the SUBALGEBRA GENERATED BY
   THE IMAGE, and the solution set it yields is what the free-algebra
   construction runs on.

   THIS FILE IS THE REMARK, NOT THE LEMMA.  The definitions are the
   frozen ones of Adjunction/SpanningArrow.v -- [SubFactorsThrough],
   [Spanning] and [SpanningArrowsOutOf] -- and nothing here renames or
   restates them.  The general Lemma is the other half of
   #448 and is not repeated.

   ** Why the Remark is proved DIRECTLY and not through the Lemma

   The Lemma takes the intersection of all subobjects a given arrow
   factors through, which in this library is
   Theory/Subobject/Lattice.v's [sub_wide_intersection] (and its
   [sub_intersection] under Structure/Pullback/Wide.v's
   [HasWidePullbacks]).  Both want wide pullbacks in the ambient
   category, and [SVariety] has none in tree: over this worktree,
   every file OTHER THAN THIS ONE naming [HasPullbacks] or
   [HasWidePullbacks] and also naming [SVariety] numbers ZERO
   (find . -name '*.v' | xargs grep -ln 'HasWidePullbacks\|HasPullbacks'
   | xargs grep -l 'SVariety' | wc -l, with this work's three files --
   this one, Adjunction/SpanningArrow.v and
   Test/ProbeVarietySpanning448.v -- excluded through -not -path on the
   find; unexcluded, the command reports exactly those three and
   nothing older).
   Building that instance is a
   development of its own and is out of scope here, so the spanning
   factorization below is constructed by hand, as Mac Lane's own prose
   does it -- by generating a subalgebra rather than by intersecting
   subobjects -- and the two Lattice.v facts that ARE used are
   TRANSPORTED, never re-proved: [sub_top_greatest] and [sub_le_antisym], both consumed by Adjunction/SpanningArrow.v's
   [spanning_forces_top] (first proved in this file and lifted there at
   integration, together with [sub_le_top_iso]).

   ** What a subalgebra is here, and why the closure is INDUCTIVE

   Instance/Variety/Free.v's [SVariety E] is a full subcategory of
   setoid algebras (its [SVariety_sub], which that file proves full),
   so a
   subalgebra is a membership predicate on the carrier that respects `≈`
   and is closed under every operation: [SubAlg] below, three fields.
   It carries a setoid algebra ([sa_soa]), it satisfies E because A does
   ([sa_satisfies], by Instance/Comp.v's [lhs_natural] and
   [rhs_natural] along the inclusion -- CONSUMING those fields exactly
   as Free.v's product does, never proving one), and its inclusion is
   monic ([sa_incl_monic]), so it is a [SubObj] of A in the sense of
   Theory/Subobject.v.

   The subalgebra GENERATED by the image of h : X → G A is [SubGen], an
   inductive predicate with three constructors (a generator is in it, it
   respects `≈`, it is closed under the operations).  The other textbook
   definition -- the intersection of all subalgebras containing the
   image -- was not chosen, and the reason is a universe one rather than
   a matter of taste: that predicate quantifies over [SubAlg E A], whose
   own [sa_mem] field lands in the universe the predicate would have to
   inhabit, so the intersection is not itself a [SubAlg] at the same
   level.  The inductive closure has no such problem and it is what
   makes the leastness clause ([sgen_least]) a plain recursion.

   ** Monos of [SVariety] are exactly the injections

   The spanning proof needs to turn a monomorphism into an injection,
   and that direction is not formal: it needs a PROBE object.  No such
   bridge existed for [SAlgHom] (measured: besides this file, no file
   naming [SAlgHom] or [SVariety] also names [Monic]); the tree has
   bridges for other categories -- 40 non-Test files naming both [Monic]
   and [injective] besides this work's two (grep -rlE '\bMonic\b'
   --include='*.v' . | grep -v /Test/ | xargs grep -l injective), including the
   generic Theory/Concrete/Morphisms.v [concrete_injective_monic] --
   and none applies, because no file gives [SVariety E] a [Concrete]
   instance.  In
   Instance/Sets.v ([injectivity_is_monic]) the probe is the
   singleton; here it is the FREE ALGEBRA ON ONE GENERATOR,
   [Free_Variety E unit_setoid_object], and the two constant maps out of
   it are separated by Free.v's [free_alg_hom_unique].  That is
   [svariety_monic_injective]; the converse [svariety_injective_monic]
   is immediate from [Sub]'s pointwise hom-setoid, and
   [svariety_monic_iff_injective] is the biconditional.  With it,
   [svariety_iso] is the analogue of Instance/Sets.v's
   [bijective_is_iso]: an injective and split-surjective homomorphism is
   an isomorphism OF ALGEBRAS, the inverse being a homomorphism because
   injectivity transports the two laws back across f.  [injective] and
   [surjective] are Lib/Setoid.v, not new vocabulary.

   ** The spanning factorization, and what it is a factorization OF

   [variety_spanning] proves [Spanning SVariety_Forget] of the
   corestriction of h to the generated subalgebra.  The argument is
   Mac Lane's: a subobject m of the generated subalgebra that the
   corestriction factors through has, pushed forward into A, an IMAGE
   that is a subalgebra of A containing every h x ([img_subalg]); by
   leastness it contains the whole closure; so the mono of m is
   surjective; being also monic it is injective, hence invertible, and
   [sub_le sub_top m] follows.  [variety_spanning_forces_top] then reads
   that back in Mac Lane's own words -- m ≈ [sub_top], so no PROPER
   subobject receives the corestriction.

   [variety_solution_set] is Remark 1 itself: a
   Adjunction/GAFT.v [SolutionSet] for [SVariety_Forget E] at every
   set X, whose [sol_index] IS [SpanningArrowsOutOf SVariety_Forget X].
   Three [Example]s read that back at [eq_refl] -- the index, the object
   map and the member covering a given h -- so the claim is not merely
   that a solution set exists but that it is the one Mac Lane names.

   ** Not delivered

   THE CARDINALITY BOUND IS NOT DELIVERED.  Mac Lane's Remark bounds the
   generated subalgebra by the cardinality of the set of terms over X
   (for a finitary signature, at most max(|X|, ℵ₀) many), which is what
   makes the spanning arrows out of X range over a SET of isomorphism
   types and so makes the solution set genuinely small.  Nothing of that
   kind is stated here.  The tree has no cardinal arithmetic, and
   Instance/Comp.v gives operations ARBITRARY TYPES as arities, so
   there is no finitary hypothesis to count with either --
   Instance/Variety/Free.v already says so in terms.  What replaces
   the bound is weaker and is stated as what it is: [sgen_free_cover] is
   a homomorphism from the free algebra on X onto the generated
   subalgebra and [sgen_free_cover_surjective] proves it (split)
   surjective, so the generated subalgebra is a quotient of the term
   algebra.  That establishes the SHAPE of Mac Lane's argument -- terms
   exhaust the closure -- and establishes nothing about size: no
   smallness of [sol_index] is claimed, and [About] reports it at a
   [Type] one universe above the carrier (u3 < u6 in
   [variety_solution_set]'s constraints), a strict bound owned by
   [SolutionSet]'s own [sol_index : Type] field, not introduced here.
   CORRECTION (#450): that readback is the one before #450, when the
   type read [SolutionSet@{u6 u6 u6 u3}].  Re-measured by [About] under
