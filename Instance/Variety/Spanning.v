Definition svariety_probe (B : SVariety E) (x : carrier (soa_obj (`1 B))) :
  Free_Variety E unit_setoid_object ~{SVariety E}~> B :=
  free_alg_hom B (svariety_const B x).

Lemma svariety_injective_monic {B C : SVariety E} (f : B ~{SVariety E}~> C) :
  injective (salg_map (`1 f)) → Monic f.
Proof.
  intros Hi.
  constructor; intros Z g1 g2 Hg z.
  exact (@inj _ _ _ _ _ Hi _ _ (Hg z)).
Qed.

Lemma svariety_monic_injective {B C : SVariety E} (f : B ~{SVariety E}~> C) :
  Monic f → injective (salg_map (`1 f)).
Proof.
  intros Hm.
  constructor; intros x y Hxy.
  assert (Heq : svariety_probe B x ≈ svariety_probe B y).
  { apply (monic (Monic:=Hm)).
    apply (free_alg_hom_unique C).
    intro u; simpl; exact Hxy. }
  exact (Heq (UA.generator S unit_setoid_object ttt)).
Qed.

Theorem svariety_monic_iff_injective {B C : SVariety E}
  (f : B ~{SVariety E}~> C) : injective (salg_map (`1 f)) ↔ Monic f.
Proof.
  split.
  - exact (svariety_injective_monic f).
  - exact (svariety_monic_injective f).
Qed.

Program Definition svariety_inverse {B C : SVariety E}
  (f : B ~{SVariety E}~> C)
  (Hi : injective (salg_map (`1 f))) (Hs : surjective (salg_map (`1 f))) :
  C ~{SVariety E}~> B :=
  ({| salg_map := fun y => `1 (@surj _ _ _ _ Hs y) |}; I).
Next Obligation.
  intros B C f Hi Hs y1 y2 Hy; simpl.
  apply (@inj _ _ _ _ _ Hi).
  transitivity y1; [ exact (`2 (@surj _ _ _ _ Hs y1)) | ].
  transitivity y2; [ exact Hy | ].
  symmetry; exact (`2 (@surj _ _ _ _ Hs y2)).
Qed.
Next Obligation.
  intros B C f Hi Hs o args; simpl.
  apply (@inj _ _ _ _ _ Hi).
  transitivity (soa_op (`1 C) o args);
    [ exact (`2 (@surj _ _ _ _ Hs _)) | ].
  transitivity (soa_op (`1 C) o
                  (fun i => salg_map (`1 f) (`1 (@surj _ _ _ _ Hs (args i))))).
  - apply (soa_op_respects (`1 C) o); intro i.
    symmetry; exact (`2 (@surj _ _ _ _ Hs (args i))).
  - symmetry.
    exact (salg_commute (`1 f) o (fun i => `1 (@surj _ _ _ _ Hs (args i)))).
Qed.

Lemma svariety_inverse_section {B C : SVariety E} (f : B ~{SVariety E}~> C)
  (Hi : injective (salg_map (`1 f))) (Hs : surjective (salg_map (`1 f))) :
  f ∘ svariety_inverse f Hi Hs ≈ id[C].
Proof. intro y; exact (`2 (@surj _ _ _ _ Hs y)). Qed.

Lemma svariety_inverse_retraction {B C : SVariety E} (f : B ~{SVariety E}~> C)
  (Hi : injective (salg_map (`1 f))) (Hs : surjective (salg_map (`1 f))) :
  svariety_inverse f Hi Hs ∘ f ≈ id[B].
Proof.
  intro x; simpl.
  apply (@inj _ _ _ _ _ Hi).
  exact (`2 (@surj _ _ _ _ Hs (salg_map (`1 f) x))).
Qed.

Program Definition svariety_iso {B C : SVariety E} (f : B ~{SVariety E}~> C)
  (Hi : injective (salg_map (`1 f))) (Hs : surjective (salg_map (`1 f))) :
  B ≅[SVariety E] C := {|
  to := f;
  from := svariety_inverse f Hi Hs
|}.
Next Obligation. intros; apply svariety_inverse_section. Qed.
Next Obligation. intros; apply svariety_inverse_retraction. Qed.

