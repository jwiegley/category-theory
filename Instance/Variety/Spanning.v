Section Terms.

Context {S : UA.OpSignature}.
Context (E : UA.EqSignature S).
Context (A : SVariety E).
Context (X : Sets).
Context (h : X ~{Sets}~> SVariety_Forget E A).

Lemma sgen_covered_by_terms (t : carrier (soa_obj (`1 A))) (D : SubGen h t) :
  { u : UA.Tree S X & free_alg_ext A h u ≈ t }.
Proof.
  induction D as [ x | u v Huv D IH | o k Hk IH ].
  - exists (UA.generator S X x); reflexivity.
  - exists (`1 IH); transitivity u; [ exact (`2 IH) | exact Huv ].
  - exists (UA.node S X o (fun i => `1 (IH i))).
    apply (soa_op_respects (`1 A) o); intro i; exact (`2 (IH i)).
Defined.

Fixpoint sgen_of_term (t : UA.Tree S X) : SubGen h (free_alg_ext A h t) :=
  match t with
  | UA.generator _ _ x => sgen_base h x
  | UA.node _ _ o k    =>
      sgen_op h o (fun i => free_alg_ext A h (k i))
        (fun i => sgen_of_term (k i))
  end.

Program Definition sgen_free_cover :
  Free_Variety E X ~{SVariety E}~> sgen_alg h :=
  ({| salg_map := fun t => (free_alg_ext A h t; sgen_of_term t) |}; I).
Next Obligation. intros t u Htu; apply free_alg_ext_respects; exact Htu. Qed.
Next Obligation. intros o args; simpl; reflexivity. Qed.

Lemma sgen_free_cover_surjective :
  surjective (salg_map (`1 sgen_free_cover)).
Proof.
  constructor; intro p.
  destruct (sgen_covered_by_terms (`1 p) (`2 p)) as [u Hu].
  exists u; exact Hu.
Defined.

End Terms.

