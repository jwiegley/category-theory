Context (A : SVariety E).
Context (X : Sets).
Context (h : X ~{Sets}~> SVariety_Forget E A).

Theorem variety_spanning :
  Spanning (SVariety_Forget E) (sgen_corestrict h).
Proof.
  intros m Hm.
  destruct Hm as [j Hj].
  pose (n := sa_incl (sgen_subalg h) ∘ sub_mono m).
  assert (Hcov : ∀ x : X, sa_mem (img_subalg n) (h x)).
  { intro x; exists (j x); exact (Hj x). }
  assert (Hs : surjective (salg_map (`1 (sub_mono m)))).
  { constructor; intro p.
    destruct (sgen_least h (img_subalg n) Hcov (`1 p) (`2 p)) as [d Hd].
    exists d; exact Hd. }
  pose (Hi := svariety_monic_injective (sub_mono m) (sub_is_monic m)).
  exists (svariety_inverse (sub_mono m) Hi Hs).
  exact (svariety_inverse_section (sub_mono m) Hi Hs).
Defined.

Definition variety_spanning_arrow :
  SpanningArrowsOutOf (SVariety_Forget E) X :=
  (sgen_alg h; (sgen_corestrict h; variety_spanning)).

(* Mac Lane's own phrasing, recovered: no PROPER subobject of the generated
   subalgebra receives the corestriction.  [spanning_forces_top] is the only
   step, and it is where the two Lattice.v facts are transported. *)
Definition variety_spanning_forces_top (m : SubObj (sgen_alg h)) :
  SubFactorsThrough (SVariety_Forget E) (sgen_corestrict h) m → m ≈ sub_top :=
  spanning_forces_top (SVariety_Forget E) (sgen_corestrict h)
    variety_spanning m.

End VarietySpanning.

