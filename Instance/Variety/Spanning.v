Record SubAlg := {
  sa_mem : carrier (soa_obj (`1 A)) → Type;
  sa_respects : ∀ u v, u ≈ v → sa_mem u → sa_mem v;
  sa_closed : ∀ (o : UA.operation S)
                (k : UA.arity o → carrier (soa_obj (`1 A))),
    (∀ i, sa_mem (k i)) → sa_mem (soa_op (`1 A) o k)
}.

Program Definition sa_setoid (B : SubAlg) :
  Setoid { t : carrier (soa_obj (`1 A)) & sa_mem B t } := {|
  equiv := fun p q => `1 p ≈ `1 q
|}.
Next Obligation.
  intros B; constructor; repeat intro.
  - reflexivity.
  - symmetry; auto.
  - transitivity (`1 y); auto.
Qed.

Definition sa_obj (B : SubAlg) : SetoidObject :=
  {| carrier   := { t : carrier (soa_obj (`1 A)) & sa_mem B t }
   ; is_setoid := sa_setoid B |}.

(* Since #450 a setoid algebra carries [soa_prop]; a subalgebra's `≈` is
   the ambient one read on first projections, so its propositional mirror
   is the ambient algebra's, transported by [sigma_first_PropEquiv]. *)
Program Definition sa_soa (B : SubAlg) : SetoidOpAlgebra S := {|
  soa_obj := sa_obj B;
  soa_op  := fun o k => (soa_op (`1 A) o (fun i => `1 (k i));
                         sa_closed B o (fun i => `1 (k i)) (fun i => `2 (k i)));
  soa_prop := sigma_first_PropEquiv (sa_setoid B) (fun _ _ h => h) (fun _ _ h => h)
                (soa_prop (`1 A))
|}.
Next Obligation.
  intros B o k1 k2 H; simpl.
  apply (soa_op_respects (`1 A) o); exact H.
Qed.

Program Definition sa_incl_alghom (B : SubAlg) :
  UA.AlgHom (soa_alg (sa_soa B)) (soa_alg (`1 A)) :=
  {| UA.map := fun p => `1 p |}.
Next Obligation. intros B o args; reflexivity. Qed.

Theorem sa_satisfies (B : SubAlg) : ssatisfies E (sa_soa B).
Proof.
  intros e args.
  assert (HL : `1 (@UA.lhs S E (soa_alg (sa_soa B)) e args)
               = @UA.lhs S E (soa_alg (`1 A)) e (fun i => `1 (args i)))
    by exact (@UA.lhs_natural S E (soa_alg (sa_soa B)) (soa_alg (`1 A))
                (sa_incl_alghom B) e args).
  assert (HR : `1 (@UA.rhs S E (soa_alg (sa_soa B)) e args)
               = @UA.rhs S E (soa_alg (`1 A)) e (fun i => `1 (args i)))
    by exact (@UA.rhs_natural S E (soa_alg (sa_soa B)) (soa_alg (`1 A))
                (sa_incl_alghom B) e args).
  change (`1 (@UA.lhs S E (soa_alg (sa_soa B)) e args)
          ≈ `1 (@UA.rhs S E (soa_alg (sa_soa B)) e args)).
  rewrite HL, HR.
  exact (`2 A e (fun i => `1 (args i))).
Qed.

Definition sa_alg (B : SubAlg) : SVariety E := (sa_soa B; sa_satisfies B).

Program Definition sa_incl (B : SubAlg) : sa_alg B ~{SVariety E}~> A :=
  ({| salg_map := fun p => `1 p |}; I).
Next Obligation. intros B p q H; exact H. Qed.
Next Obligation. intros B o args; simpl; reflexivity. Qed.

Lemma sa_incl_injective (B : SubAlg) : injective (salg_map (`1 (sa_incl B))).
Proof. constructor; intros p q H; exact H. Qed.

Definition sa_incl_monic (B : SubAlg) : Monic (sa_incl B) :=
  svariety_injective_monic (sa_incl B) (sa_incl_injective B).

Definition sa_subobj (B : SubAlg) : @SubObj (SVariety E) A := {|
  sub_dom      := sa_alg B;
  sub_mono     := sa_incl B;
  sub_is_monic := sa_incl_monic B
|}.

(** *** The image of a homomorphism is a subalgebra *)

Program Definition img_subalg {B : SVariety E} (f : B ~{SVariety E}~> A) :
  SubAlg := {|
  sa_mem := fun t => { d : carrier (soa_obj (`1 B)) & salg_map (`1 f) d ≈ t }
|}.
Next Obligation.
  intros B f u v Huv D; simpl in *.
  exists (`1 D).
  transitivity u; [ exact (`2 D) | exact Huv ].
