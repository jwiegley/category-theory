(** ** Block H: fields are not a variety

    Mac Lane's remark is that the free-algebra construction gives free
    rings, free abelian groups and free modules but NOT free fields.  The
    issue states the reason as "the multiplicative inverse is a partial
    operation", which is the motivation; the PROOF is the one Mac Lane's
    own framework supplies and it is a different argument — varieties are
    closed under products, and fields are not.  [F2 × F2] has a nonzero
    element with no inverse.

    TWO statements are shipped, and the difference between them is the
    substance of an audit finding.  The weaker one,
    [division_is_not_equationally_definable], is about the DIVISION
    PROPERTY alone; an earlier revision called that predicate [IsField]
    and claimed the theorem ruled out every [EqSignature RingOp] whose
    models are exactly the fields.  It did not, and the counterexamples
    are cheap: the one-element algebra has the division property (and
    [1 = 0] in it), and so does a "ring" whose addition has no unit — so
    no [E] whose models are exactly the fields can satisfy that theorem's
    soundness hypothesis, and the theorem said nothing about such an [E].
    The stronger one, [fields_are_not_a_variety], is stated over an
    [IsField] that imposes the ring axioms, additive inverses, [1 ≉ 0]
    and division, and it does say what its name says.

    The quantifier is still worth reading exactly: this rules out every
    [EqSignature RingOp] whose models are exactly the fields, over this
    FIXED signature.  It is not Birkhoff's HSP theorem and does not imply
    it.  Note also that [RingOp] carries no negation operation, which is
    why additive inverses appear in [IsField] as a Σ-clause rather than
    as an operation. *)

Inductive ring_op : Set := rzero | rone | radd | rmul.

Definition RingOp : UA.OpSignature := {|
  UA.operation := ring_op;
  UA.arity := fun o => match o with
                       | rzero | rone => UA.nullary
                       | radd | rmul  => UA.binary
                       end
|}.

(* The signature argument of [UA.arity] must be given explicitly in the
   return clause: [UA.operation RingOp] reduces to [ring_op], and the
   elaborator will not run that delta backwards to recover [RingOp] from
   the match variable.  Instance/Comp.v annotates for the same
   reason. *)
Definition F2_op (o : UA.operation RingOp) : (UA.arity o → bool) → bool :=
  match o as o0 return (@UA.arity RingOp o0 → bool) → bool with
  | rzero => fun _ => false
  | rone  => fun _ => true
  | radd  => fun k => xorb (k UA.Fst) (k UA.Snd)
  | rmul  => fun k => andb (k UA.Fst) (k UA.Snd)
  end.

(* Respectfulness needs NO extensionality even at the discrete setoid,
   because each operation reads its bundle only at the finitely many
   elements of the arity. *)
Program Definition F2 : SetoidOpAlgebra RingOp := {|
  soa_obj := {| carrier := bool ; is_setoid := eq_Setoid bool |};
  soa_op  := F2_op
|}.
Next Obligation.
  intros o k1 k2 H; destruct o as [ | | | ]; simpl in *; try reflexivity;
    rewrite (H UA.Fst), (H UA.Snd); reflexivity.
Qed.

Definition r_zero (A : SetoidOpAlgebra RingOp) : carrier (soa_obj A) :=
  soa_op A rzero (fun i => match i return carrier (soa_obj A) with end).

Definition r_one (A : SetoidOpAlgebra RingOp) : carrier (soa_obj A) :=
  soa_op A rone (fun i => match i return carrier (soa_obj A) with end).

Definition r_mul (A : SetoidOpAlgebra RingOp)
  (x y : carrier (soa_obj A)) : carrier (soa_obj A) :=
  soa_op A rmul (fun i => match i with UA.Fst => x | UA.Snd => y end).

Definition r_add (A : SetoidOpAlgebra RingOp)
  (x y : carrier (soa_obj A)) : carrier (soa_obj A) :=
  soa_op A radd (fun i => match i with UA.Fst => x | UA.Snd => y end).

(* THE DIVISION PROPERTY ALONE — every nonzero element has a right
   inverse for multiplication.  An earlier revision called this [IsField]
   and an audit was right to object: it imposes no ring axiom and does
   not ask [1 ≉ 0], so the ONE-ELEMENT algebra satisfies it, and so does
   a "ring" with no additive unit.  The name now says what it is, and the
   theorem built from it below says what that theorem actually rules out.

   It is [Type]-valued because it returns a chosen inverse.  An earlier
   revision gave the reason as "since it must feed
   [not_equationally_definable]", which is false — that schema takes a
   [Prop]-valued [P] perfectly well. *)
Definition HasDivision (A : SetoidOpAlgebra RingOp) : Type :=
  ∀ x : carrier (soa_obj A),
    (x ≈ r_zero A → False) → { y : carrier (soa_obj A) & r_mul A x y ≈ r_one A }.

Definition F2_HasDivision : HasDivision F2.
Proof.
  intros x Hx.
  destruct x.
  - exists true; reflexivity.
  - destruct (Hx eq_refl).
Defined.

(* [(true, false)] is nonzero and has no inverse: the second component of
   any product with it is [false], never [true]. *)
Definition F2xF2_no_division : HasDivision (soa_prod F2 F2) → False.
Proof.
  intro HF.
  destruct (HF (true, false)) as [y Hy].
  - intro Hz; destruct Hz as [H1 H2]; simpl in H1; discriminate H1.
  - destruct Hy as [H1 H2]; simpl in H2; discriminate H2.
Defined.

Definition division_is_not_equationally_definable :
  ∀ E : UA.EqSignature RingOp,
    (∀ C : SetoidOpAlgebra RingOp, HasDivision C → ssatisfies E C) →
    (∀ C : SetoidOpAlgebra RingOp, ssatisfies E C → HasDivision C) →
    False :=
  not_equationally_definable HasDivision F2 F2
    F2_HasDivision F2_HasDivision F2xF2_no_division.

(** *** And now the statement Mac Lane's remark actually needs

    [IsField] imposes the ring axioms, additive inverses (as a Σ-clause,
    since [RingOp] carries no negation operation), [1 ≉ 0], and division.
    With it, [fields_are_not_a_variety] says what its name says. *)

Definition IsField (A : SetoidOpAlgebra RingOp) : Type :=
  (((∀ x y z, r_add A (r_add A x y) z ≈ r_add A x (r_add A y z)) *
    (∀ x y, r_add A x y ≈ r_add A y x) *
    (∀ x, r_add A x (r_zero A) ≈ x) *
    (∀ x, { y & r_add A x y ≈ r_zero A }) *
    (∀ x y z, r_mul A (r_mul A x y) z ≈ r_mul A x (r_mul A y z)) *
    (∀ x y, r_mul A x y ≈ r_mul A y x) *
    (∀ x, r_mul A x (r_one A) ≈ x) *
    (∀ x y z, r_mul A x (r_add A y z) ≈ r_add A (r_mul A x y) (r_mul A x z)) *
    ((r_one A ≈ r_zero A) → False))
   * HasDivision A)%type.

Definition F2_IsField : IsField F2.
Proof.
  unfold IsField, HasDivision; simpl.
  refine ((((((((( _ , _ ) , _ ) , _ ) , _ ) , _ ) , _ ) , _ ) , _ ) , _ );
    try solve [ intros; repeat match goal with [ x : bool |- _ ] => destruct x end;
                simpl; reflexivity ].
  all: try solve [ intro x; exists x; destruct x; reflexivity ].
  all: try solve [ intro H; discriminate H ].
  all: try solve [ intros x Hx; destruct x;
                   [ exists true; reflexivity | destruct (Hx eq_refl) ] ].
Defined.

Definition F2xF2_not_field : IsField (soa_prod F2 F2) → False :=
  fun HF => F2xF2_no_division (snd HF).

Definition fields_are_not_a_variety :
  ∀ E : UA.EqSignature RingOp,
    (∀ C : SetoidOpAlgebra RingOp, IsField C → ssatisfies E C) →
    (∀ C : SetoidOpAlgebra RingOp, ssatisfies E C → IsField C) →
    False :=
  not_equationally_definable IsField F2 F2 F2_IsField F2_IsField F2xF2_not_field.
