(** ** Block C: the free algebra — terms modulo the congruence

    The carrier is Instance/Comp.v's [Tree], UNCHANGED; what is new is
    the equivalence it is equipped with.  Nothing is rebuilt, which is
    what makes this honest to the issue's phrase "the term algebra
    quotiented by the congruence generated by E": the quotient is a
    coarser `≈` on the same carrier, not a new type. *)

Section FreeVariety.

Context {S : UA.OpSignature}.
Context (E : UA.EqSignature S).
Context (X : SetoidObject).

(* Symmetry and transitivity are CONSTRUCTORS, not theorems.  That is the
   whole trick: no inversion is ever performed on a derivation, so the
   [Eqdep]/[JMeq_eq] hazard Instance/Variety/Clone.v feared does not
   arise.  [Prop]-valued since #450; an earlier revision said
   "[Type]-valued because [Setoid]'s [equiv] is a crelation", and the
   header's correction under "The congruence on terms is axiom-free"
   says why that was no reason. *)
Inductive tree_equiv : UA.Tree S X → UA.Tree S X → Prop :=
  | tc_gen : ∀ x y : X, x ≈ y →
      tree_equiv (UA.generator S X x) (UA.generator S X y)
  | tc_op : ∀ (o : UA.operation S) (k1 k2 : UA.arity o → UA.Tree S X),
      (∀ j, tree_equiv (k1 j) (k2 j)) →
      tree_equiv (UA.node S X o k1) (UA.node S X o k2)
  | tc_law : ∀ (e : UA.eq S E) (args : UA.eq_arity e → UA.Tree S X),
      tree_equiv (@UA.lhs S E (UA.Free S X) e args)
                 (@UA.rhs S E (UA.Free S X) e args)
  | tc_sym : ∀ t u, tree_equiv t u → tree_equiv u t
  | tc_trans : ∀ t u v, tree_equiv t u → tree_equiv u v → tree_equiv t v.

(* Reflexivity is DERIVED, by plain induction on the tree — again no
   inversion.  The generator case needs [X]'s own reflexivity, which is
   where the setoid on the generators enters. *)
Fixpoint tc_refl (t : UA.Tree S X) : tree_equiv t t :=
  match t with
  | UA.generator _ _ x => tc_gen x x (reflexivity x)
  | UA.node _ _ o k    => tc_op o k k (fun j => tc_refl (k j))
  end.

Program Definition Tree_Setoid : Setoid (UA.Tree S X) := {|
  equiv := tree_equiv
|}.
Next Obligation.
  constructor.
  - exact tc_refl.
  - exact tc_sym.
  - exact tc_trans.
Qed.

Definition FreeSOA : SetoidOpAlgebra S := {|
  soa_obj := {| carrier := UA.Tree S X ; is_setoid := Tree_Setoid |};
  soa_op  := UA.node S X;
  soa_op_respects := tc_op;
  soa_prop := @PropEquiv_of_relation _ Tree_Setoid tree_equiv
                (fun _ _ h => h) (fun _ _ h => h)
|}.

(* The laws hold in the free algebra BY CONSTRUCTION — [tc_law] is
   literally the satisfaction proof, which is the sense in which the
   congruence is "generated by E". *)
Definition FreeSOA_satisfies : ssatisfies E FreeSOA := tc_law.

Definition Free_Variety : SVariety E := (FreeSOA; FreeSOA_satisfies).

End FreeVariety.

Arguments tree_equiv {_} _ _ _ _.
Arguments tc_refl {_ _ _} _.
Arguments Tree_Setoid {_} _ _.
Arguments FreeSOA {_} _ _.
Arguments FreeSOA_satisfies {_} _ _.
Arguments Free_Variety {_} _ _.

(** ** Block D: the universal property

    Every map from the generators into an algebra of the variety extends
    to a unique homomorphism.  The extension is Instance/Comp.v's
    [induced_map] verbatim — nothing is re-recursed — so the only work is
    showing it respects the congruence, and THAT is where the variety's
    satisfaction of the laws is consumed. *)

Section FreeUP.

Context {S : UA.OpSignature}.
Context (E : UA.EqSignature S).
Context (X : SetoidObject).
Context (A : SVariety E).
Context (h : X ~{Sets}~> soa_obj (`1 A)).

Definition free_alg_ext : UA.Tree S X → soa_obj (`1 A) :=
  UA.induced_map S X (soa_alg (`1 A)) h.

(* The congruence is respected.  Each constructor is discharged by the
   corresponding structure of [A]: [tc_gen] by [h]'s respectfulness,
   [tc_op] by [soa_op_respects], and [tc_law] — the only interesting
   case — by [A]'s own satisfaction proof, transported along the
   naturality of [lhs]/[rhs] at [induced_hom].

   Since #450 the derivation is a [Prop] and the goal is the [Type]-valued
   `≈` of [A], so the proof first moves to [A]'s propositional mirror with
   [pequiv_to], eliminates the derivation there, and returns each branch
   with [pequiv_from].  An earlier revision called this lemma "the single
   place where [EqSignature]'s naturality fields are CONSUMED, and the
   reason the whole development is axiom-free".  It was not the single
   place even in this file -- [soa_prod_satisfies] below consumes them too
   -- and since #450 Instance/Variety/Limit.v's [svlim_satisfies] and
   Instance/Variety/Colimit.v's [vker_cong] do as well.  What makes the
   development axiom-free is that every consumer CONSUMES those fields and
   none proves one, as the header says. *)
Lemma free_alg_ext_respects (t u : UA.Tree S X) :
  tree_equiv E X t u → free_alg_ext t ≈ free_alg_ext u.
Proof.
  intro D.
  apply (@pequiv_to _ _ (soa_prop (`1 A))).
  induction D as [ x y Hxy | o k1 k2 Hk IH | e args | t u D IH | t u v D1 IH1 D2 IH2 ].
  - apply pequiv_from; exact (proper_morphism h x y Hxy).
  - apply pequiv_from; apply (soa_op_respects (`1 A) o);
      intro j; exact (pequiv_to _ _ (IH j)).
  - apply pequiv_from; unfold free_alg_ext.
    (* [UA.map (induced_hom …)] and [induced_map …] are convertible but
       not syntactically equal, and [simpl] on the naturality equation
       also unfolds [soa_alg] and so walks away from the goal's shape.
       So each equation is ASSERTED at exactly the shape the goal has and
       discharged by [exact], which uses full conversion. *)
    assert (HL : UA.induced_map S X (soa_alg (`1 A)) h
                   (@UA.lhs S E (UA.Free S X) e args)
                 = @UA.lhs S E (soa_alg (`1 A)) e
                     (fun i => UA.induced_map S X (soa_alg (`1 A)) h (args i)))
      by exact (@UA.lhs_natural S E (UA.Free S X) (soa_alg (`1 A))
                  (UA.induced_hom S X (soa_alg (`1 A)) h) e args).
    assert (HR : UA.induced_map S X (soa_alg (`1 A)) h
                   (@UA.rhs S E (UA.Free S X) e args)
                 = @UA.rhs S E (soa_alg (`1 A)) e
                     (fun i => UA.induced_map S X (soa_alg (`1 A)) h (args i)))
      by exact (@UA.rhs_natural S E (UA.Free S X) (soa_alg (`1 A))
                  (UA.induced_hom S X (soa_alg (`1 A)) h) e args).
    rewrite HL, HR.
    exact (`2 A e (fun i => UA.induced_map S X (soa_alg (`1 A)) h (args i))).
  - symmetry; exact IH.
  - transitivity (free_alg_ext u); assumption.
Qed.

Program Definition free_alg_hom : Free_Variety E X ~{SVariety E}~> A :=
  ({| salg_map := free_alg_ext |}; I).
Next Obligation. repeat intro; apply free_alg_ext_respects; assumption. Qed.
Next Obligation. intros o args; simpl; reflexivity. Qed.

(* Uniqueness: two homomorphisms out of the free algebra that agree on
   generators agree everywhere, by induction on the term. *)
Theorem free_alg_hom_unique (f g : Free_Variety E X ~{SVariety E}~> A) :
  (∀ x : X, salg_map (`1 f) (UA.generator S X x)
              ≈ salg_map (`1 g) (UA.generator S X x)) →
  f ≈ g.
Proof.
  intros Hgen t.
  induction t as [ x | o k IH ]; simpl.
  - exact (Hgen x).
  - transitivity (soa_op (`1 A) o (fun j => salg_map (`1 f) (k j))).
    + exact (salg_commute (`1 f) o k).
    + transitivity (soa_op (`1 A) o (fun j => salg_map (`1 g) (k j))).
      * apply (soa_op_respects (`1 A) o); exact IH.
      * symmetry; exact (salg_commute (`1 g) o k).
Qed.

End FreeUP.

