(** * The free-algebra adjunction for a variety *)

(* nLab:      https://ncatlab.org/nlab/show/variety+of+algebras
   nLab:      https://ncatlab.org/nlab/show/free+object
   Wikipedia: https://en.wikipedia.org/wiki/Free_object

   Mac Lane §V.6, book p. 124 (PDF pp. 133–134).  For any variety the
   underlying-set functor has a left adjoint — the free algebra on a set —
   and Mac Lane gets it from the adjoint functor theorem, the solution set
   being the subalgebra generated by the image.  This file gets it
   directly, and the reason is measured rather than stylistic (see "Why
   not GAFT" below).

   ** The one design decision, and what is actually true about it

   AN EARLIER REVISION OF THIS HEADER SAID, IN CAPITALS, THAT THE FREE
   OBJECT OF A VARIETY "CANNOT LIVE IN #440's [Variety E]", because
   quotienting a type by a relation is what Coq does not offer.  THAT IS
   FALSE, and it was refuted by construction rather than by argument: the
   free commutative magma on two generators DOES exist as an object of
   #440's Leibniz [Variety CommEq], built by sorting terms into normal
   forms under a decidable total order, with its universal arrow packaged
   through the same [universal_arrow_from_UMP] this file uses.  A cheap
   in-tree witness of the same point is
   Test/ProbeVarietyFree441.v's [free_empty_eq_leibniz]: with no
   equations at all the term algebra is already a Leibniz-variety object.

   What IS true, and is the actual reason for the design:

   (1) The TERM ALGEBRA is not a Leibniz-variety object once the
   equations bite.  [free_magma_not_comm_leibniz] proves it for the
   commutative magma — [x * y] and [y * x] are different terms — against
   a control showing the shape is inhabited at the booleans under [xorb].
   So the naive construction, the one Mac Lane's prose describes, does
   not land in [Variety E].

   (2) Making it land requires a NORMAL FORM for the presentation:
   a computable choice of representative per congruence class, which is
   solving that presentation's word problem.  That is available for the
   commutative magma and is not available uniformly — there are finitely
   presented algebraic theories with undecidable word problems, so no
   construction uniform in ⟨Ω,E⟩ can take this route.  This file's
   deliverable is exactly such a uniform construction: [Free_Variety] is
   defined for EVERY [E], with no decidability hypothesis anywhere.

   So the setoid carrier is what buys UNIFORMITY, not existence.  The
   quotient becomes a choice of `≈` on the same carrier rather than a new
   type — the design Instance/Sets/Quotient.v's header states for
   quotients of sets — and the two varieties are deliberately built in the
   same shape, both as [Sub] of a category of algebras, so they read as
   siblings; #440's [Instance/Variety.v]'s [Variety_sub] is the model this
   file follows.

   ** Why the general theory is AXIOM-FREE although #440's [GroupVariety]
      is not

   This is the fact that makes the file possible, and it is worth stating
   precisely because it looks like a contradiction of #440.  The
   equations enter here ONLY through [EqSignature]'s [lhs_natural] and
   [rhs_natural] (Instance/Comp.v), and every construction
   below CONSUMES those fields; none of them proves one.  #440's
   [functional_extensionality_dep] is the cost of BUILDING a particular
   [EqSignature] — of discharging those two naturality fields for the
   group laws — not of using one.  Hence: the general adjunction is
   Closed under the global context, and INSTANTIATING it at
   [UA.GroupEq] is not.  [FreeGroupOn] and [FreeGroup_adjunction] below
   carry the axiom for exactly that inherited reason and are not gated;
   the depth-1 [CommMagmaFree] is closed and is.

   ** The congruence on terms is axiom-free, and #440 said otherwise

   Instance/Variety/Clone.v's "Not delivered" block declined a setoid on
   [Tree] on the ground that transitivity would have to invert
   [tree_equiv] at a node, wanting injectivity of [existT] on an
   [operation S] with no decidable equality, and so would risk
   [Eqdep]/[JMeq_eq].  That reason was WRONG and the block now says so:
   making symmetry and transitivity CONSTRUCTORS rather than theorems
   means no inversion is ever performed.  [tc_refl] is then derived by
   plain induction on the tree.  The relation must be [Type]-valued, not
   [Prop]-valued, because [Setoid]'s [equiv] is a crelation and
   [free_alg_ext_respects] eliminates a derivation into it.

   [tc_gen] relates generators that are `≈` in the GENERATOR setoid, not
   merely equal ones; that is what makes the free construction a functor
   on [Sets] rather than on bare types.

   ** Why not GAFT

   Mac Lane's own route is the adjoint functor theorem, and the tree has
   GAFT (Adjunction/GAFT.v).  It loses here on four counts, of which the
   universe pin is the least.  GAFT wants [Complete (SVariety E)], which
   is not in hand; [PreservesImageLimit] for the forgetful functor,
   likewise; and a [SolutionSet] with §V.7's cardinality bound, which
   does not exist constructively in this setting at all, because
   Instance/Comp.v's arities are ARBITRARY TYPES (its header says so
   in terms) rather than finite ones, so "the subalgebra generated by the
   image" has no cardinality bound to state.  The direct route is two
   definitions over [universal_arrow_from_UMP]
   (Theory/Universal/Arrow.v), which is the same shape
   Construction/Free/Quiver.v already uses for the free category on a
   quiver.  The [Set] pin GAFT carries is real but is not why it loses.

   ** Transparency, measured

   Four [Defined] in this file, and exactly ONE is load-bearing: [FreeUA].
   Flipping it to [Qed] stops Test/ProbeVarietyFree441.v at
   [p441_left_adjoint_obj], the readback that the left adjoint's action
   on objects IS [Free_Variety] — which is only visible because the
   universal arrow's construction reduces.  The other three
   ([F2_HasDivision], [F2_IsField] and [EmptyEq]'s sibling work) flip
   cleanly and are transparent only by the convention that data-like
   constructions stay so.  Twenty-seven [Qed].

   Two names are used twice, for a [Section] and for a constant declared
   inside it: [SetoidAlgs] and [SVariety].  That is legal and the
   constant is what survives the section, but it is worth knowing when
   grepping.

   ** A degeneracy this does NOT rule out

   Axiom-freedom of the general adjunction is compatible with the free
   algebra being a single `≈`-class: for an [E] whose laws identify
   everything, [Free_Variety E X] is the one-point algebra and the
   adjunction still holds, axiom-free.  Nothing here excludes that, and
   nothing should — it is the correct answer for such an [E].  What rules
   it out at a PARTICULAR presentation is a separation result, and the
   one shipped is Test/ProbeVarietyFree441.v's [free_comm_not_collapsed]
   for the commutative magma.  No general non-collapse statement is made.

   ** Not delivered

   No [Free_Variety : Variety E] for #440's Leibniz variety.  Note the
   corrected reason: not "impossible" — it exists whenever the
   presentation has a computable normal form, and the free commutative
   magma was built that way to refute the earlier claim — but not
   uniformly in ⟨Ω,E⟩, which is what this file delivers.  The
   normal-form construction for that one presentation is about 250 lines
   concerning a single signature and is not shipped.  No
   Birkhoff HSP theorem: the non-example below is stated over a FIXED
   signature and rules out every [EqSignature RingOp] whose models are
   exactly the fields, which is what Mac Lane's remark needs and no more.
   No cardinality bound and no solution set, hence no GAFT route.  No
   functor [Variety E ⟶ SVariety E]: [leibniz_soa] is an object map only,
   so #440's category and this one are not related as categories here.
   No
   free ring, free abelian group or free module as named instances —
   those need their signatures spelled out, and the two shipped instances
   (the commutative magma and the group) are what the issue's own
   Verification block asks to run. *)

