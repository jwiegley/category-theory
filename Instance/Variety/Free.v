(** * The free-algebra adjunction for a variety *)

(* nLab:      https://ncatlab.org/nlab/show/variety+of+algebras
   nLab:      https://ncatlab.org/nlab/show/free+object
   Wikipedia: https://en.wikipedia.org/wiki/Free_object

   Mac Lane §V.6, book p. 124 (PDF pp. 133–134).  For any variety the
   underlying-set functor has a left adjoint — the free algebra on a set —
   and Mac Lane gets it from the adjoint functor theorem, the solution set
   being the subalgebra generated by the image.  This file gets it
   directly.  An earlier revision went on: "and the reason is measured
   rather than stylistic".  Since #450 Mac Lane's route is in tree as
   well, and the direct one is kept for the reasons "Why not GAFT" below
   now gives.

   ** The one design decision, and what is actually true about it

   AN EARLIER REVISION OF THIS HEADER SAID, IN CAPITALS, THAT THE FREE
   OBJECT OF A VARIETY "CANNOT LIVE IN #440's [Variety E]", because
   quotienting a type by a relation is what Coq does not offer.  THAT IS
   FALSE, and it was refuted by construction rather than by argument: the
   free commutative magma on two generators DOES exist as an object of
   #440's Leibniz [Variety CommEq], built by sorting terms into normal
   forms under a decidable total order, with its universal arrow packaged
   through the same [universal_arrow_from_UMP] this file uses.  A cheap
   in-tree witness of the same point is
   Test/ProbeVarietyFree441.v's [free_empty_eq_leibniz]: with no
   equations at all the term algebra is already a Leibniz-variety object.

   What IS true, and is the actual reason for the design:

   (1) The TERM ALGEBRA is not a Leibniz-variety object once the
   equations bite.  [free_magma_not_comm_leibniz] proves it for the
   commutative magma — [x * y] and [y * x] are different terms — against
   a control showing the shape is inhabited at the booleans under [xorb].
   So the naive construction, the one Mac Lane's prose describes, does
   not land in [Variety E].

   (2) Making it land requires a NORMAL FORM for the presentation:
   a computable choice of representative per congruence class, which is
   solving that presentation's word problem.  That is available for the
   commutative magma and is not available uniformly — there are finitely
   presented algebraic theories with undecidable word problems, so no
   construction uniform in ⟨Ω,E⟩ can take this route.  This file's
   deliverable is exactly such a uniform construction: [Free_Variety] is
   defined for EVERY [E], with no decidability hypothesis anywhere.

   So the setoid carrier is what buys UNIFORMITY, not existence.  The
   quotient becomes a choice of `≈` on the same carrier rather than a new
   type — the design Instance/Sets/Quotient.v's header states for
   quotients of sets — and the two varieties are deliberately built in the
   same shape, both as [Sub] of a category of algebras, so they read as
   siblings; #440's [Instance/Variety.v]'s [Variety_sub] is the model this
   file follows.

   ** Why the general theory is AXIOM-FREE although #440's [GroupVariety]
      is not

   This is the fact that makes the file possible, and it is worth stating
   precisely because it looks like a contradiction of #440.  The
   equations enter here ONLY through [EqSignature]'s [lhs_natural] and
   [rhs_natural] (Instance/Comp.v), and every construction
   below CONSUMES those fields; none of them proves one.  #440's
   [functional_extensionality_dep] is the cost of BUILDING a particular
   [EqSignature] — of discharging those two naturality fields for the
   group laws — not of using one.  Hence: the general adjunction is
   Closed under the global context, and INSTANTIATING it at
   [UA.GroupEq] is not.  [FreeGroupOn] and [FreeGroup_adjunction] below
   carry the axiom for exactly that inherited reason and are not gated;
   the depth-1 [CommMagmaFree] is closed and is.

   ** The congruence on terms is axiom-free, and #440 said otherwise

   Instance/Variety/Clone.v's "Not delivered" block declined a setoid on
   [Tree] on the ground that transitivity would have to invert
   [tree_equiv] at a node, wanting injectivity of [existT] on an
   [operation S] with no decidable equality, and so would risk
   [Eqdep]/[JMeq_eq].  That reason was WRONG and the block now says so:
   making symmetry and transitivity CONSTRUCTORS rather than theorems
   means no inversion is ever performed.  [tc_refl] is then derived by
   plain induction on the tree.

   CORRECTION (#450).  An earlier revision said here: "The relation must
   be [Type]-valued, not [Prop]-valued, because [Setoid]'s [equiv] is a
   crelation and [free_alg_ext_respects] eliminates a derivation into
   it."  [tree_equiv] is now [Prop]-valued.  The first half was never a
   reason: a [crelation] field accepts a [Prop]-valued relation by
   cumulativity, which is how [Tree_Setoid] now uses it.  The second
   stopped being one: the single elimination into a [Type]-sorted goal,
   [free_alg_ext_respects], now goes through the TARGET's [soa_prop]
   (next section): [pequiv_to] first turns the goal into a [Prop], and
   the derivation is eliminated into that, exactly as
   Instance/Mod/Free.v's [fv_eval_respects] did in the PR "algebraic
   carriers are sets".  The reason for the move is [soa_prop] (next
   section): [FreeSOA]'s `≈` must be interderivable with a
   [Prop]-valued relation, and a [Prop]-valued [tree_equiv] is that
   relation directly.  Necessity is argued, not measured: no alternative
   (a [Type]-valued [tree_equiv] beside a separate [Prop] mirror) was
   built or probed.  The [Prop] sort is also what
   Instance/Variety/Colimit.v's solution sets use: their kernel
   congruences are carrier-sized only as [Prop]s (Structure/Complete.v's
   size note, item 1).
   [About tree_equiv] now reports "may only be eliminated to produce
   values whose type is SProp or Prop", and Test/ProbeVarietyFree441.v's
   n4 pins the refusal of an elimination into a [Type]-sorted goal
   against a [Prop]-sorted control.  Its [_rect] and [_rec] eliminators
   are gone ([_ind] and [_sind] remain), and no gate line named them.

   [tc_gen] relates generators that are `≈` in the GENERATOR setoid, not
   merely equal ones; that is what makes the free construction a functor
   on [Sets] rather than on bare types.

   ** The carrier's `≈` is a proposition (#450)

   [SetoidOpAlgebra] carries a fourth field, [soa_prop : PropEquiv
   (is_setoid soa_obj)] (Lib/Setoid/Propositional.v), the same property
   the PR "algebraic carriers are sets" put on the object records of
   CMon, Rig and Grp.  The six construction sites that existed before
   #450 supply it: [FreeSOA] from the congruence itself
   ([PropEquiv_of_relation]), [soa_prod] as the conjunction of the
   factors', [leibniz_soa] and [F2] as [eq_PropEquiv],
   Instance/Variety/Spanning.v's [sa_soa] along the first projection
   ([sigma_first_PropEquiv]), and Test/ProbeVarietyFree441.v's
   [BoolCommMagma] as [eq_PropEquiv].  The three #450 adds are
   Instance/Variety/Limit.v's [svlim_soa] (Instance/Sets/Propositional.v's
   [limit_PropEquiv], from the components' fields) and
   Instance/Variety/Colimit.v's [VQ_soa] and [FQ_soa] (the indexing
   congruence itself).
   Measured with [About] under [Set Printing Universes] against the tree
   before #450: [SetoidAlgs] keeps its seven universe binders and gains
   exactly [Set < u1], its object universe; [SVariety] keeps fifteen and
   gains [Set < u7]; the record's sort goes from
   [Type@{max(u,u0,u1+1,u2+1)}] to [Type@{max(Set+1,u,u0,u1+1,u2+1)}];
   and [SVariety_Forget] goes from ten universe binders to eleven.
   Unlike CMon, no category here had to be pinned by hand.
   The theorems of Blocks F and H quantify over [SetoidOpAlgebra], so
   since #450 they range over algebras whose `≈` is a proposition, and
   they did NOT all become stronger.  Block F's [soa_prod_satisfies]
   quantifies over its algebras A and B outright, so it now says less:
   the old statement implies the new one by forgetting [soa_prop], and
   the new one says nothing about an algebra whose `≈` is not a
   proposition.  Block F's schema [not_equationally_definable] now asks
   for propositional witnesses A and B (weaker) while its soundness and
   completeness hypotheses range over fewer algebras (stronger), so it
   is incomparable with its old form.  Only Block H's two theorems,
   whose witness [F2] is fixed and carries [eq_PropEquiv bool], changed
   in their hypotheses alone, and each became (weakly) stronger (the
   comment opening Block H says so).

   ** Why not GAFT -- and, since #450, GAFT as well

   Mac Lane's own route is the adjoint functor theorem, and the tree has
   GAFT (Adjunction/GAFT.v).  The direct route here is two definitions
   over [universal_arrow_from_UMP] (Theory/Universal/Arrow.v), which is
   the same shape Construction/Free/Quiver.v already uses for the free
   category on a quiver.

   CORRECTION (#450).  An earlier revision of this block said GAFT
   "loses here on four counts, of which the universe pin is the least":
   it wants [Complete (SVariety E)], "which is not in hand";
   [PreservesImageLimit] for the forgetful functor, "likewise"; "a
   [SolutionSet] with §V.7's cardinality bound, which does not exist
   constructively in this setting at all", Instance/Comp.v's arities
   being ARBITRARY TYPES (its header says so in terms) so that "the
   subalgebra generated by the image" has no cardinality bound to state;
   and "the [Set] pin GAFT carries is real but is not why it loses".
   Measured since: the arities are still arbitrary types and no
   cardinality bound is stated anywhere, but none of the four counts
   stands.  Completeness and preservation are Instance/Variety/Limit.v's
   [SVariety_Complete] (limits computed on the compatible families of
   Instance/Sets/Complete.v) and [SVariety_Forget_continuous].  The
   solution set never needed a cardinality bound, only an index at the
   carrier universe (Structure/Complete.v's size note), and the
   [Prop]-valued congruences on the term algebra over [X] are such an
   index once every algebra carries [soa_prop]: that family is
   Instance/Variety/Colimit.v's [SVariety_Forget_solution_set], which
   REPLACES Mac Lane's generated-subalgebra family rather than bounding
   it.  The [Set] pin was removed from GAFT's signature by the PR
   "algebraic carriers are sets" (the size note's history paragraph),
   and [About Free_Variety_via_GAFT] instantiates no universe at [Set]:
   its one local mention of [Set] is the lower bound [Set < u9] on the
   carrier universe (the printed block also has [Set < Projections.u0],
   a bound on a stdlib global, of the kind this file's readbacks drop).
   That bound is [GAFT]'s: [GAFT] puts its solution set's index AT the
   carrier universe, and the congruence index, carrier-sized because
   every algebra carries [soa_prop], sits strictly above [Set].  Measured
   in a scratch file with the carrier at [Set]:
   [SVariety_Forget_solution_set] is accepted, and so is [GAFT] at
   [SVariety_Forget] with every argument but the solution set, while the
   full application is refused.  So Mac Lane's route is
   Instance/Variety/Colimit.v's [Free_Variety_via_GAFT], closed under the
   global context, and [Free_Variety_via_GAFT_agrees] identifies its
   left adjoint with [Free_Variety_Functor] up to natural isomorphism.

   The direct construction stays the primary one for two measured
   reasons.  It is TRANSPARENT where the other is not: [GAFT] ends in
   [Qed], so the GAFT left adjoint supports none of the [eq_refl]
   readbacks Test/ProbeVarietyFree441.v states for this one (its
   [p441_left_adjoint_obj] among them).  And GAFT does not avoid the
   construction: every member of the congruence-indexed solution set is
   this file's term algebra under a coarser `≈`, so the theorem reaches
   the free algebra only by way of the carrier built here.

   ** Transparency, measured

   Four [Defined] in this file, and exactly ONE is load-bearing: [FreeUA].
   Flipping it to [Qed] stops Test/ProbeVarietyFree441.v at
   [p441_left_adjoint_obj], the readback that the left adjoint's action
   on objects IS [Free_Variety] — which is only visible because the
   universal arrow's construction reduces.  The other three
   ([F2_HasDivision], [F2_IsField] and [EmptyEq]'s sibling work) flip
   cleanly and are transparent only by the convention that data-like
   constructions stay so.  Twenty-seven [Qed].

   Two names are used twice, for a [Section] and for a constant declared
   inside it: [SetoidAlgs] and [SVariety].  That is legal and the
   constant is what survives the section, but it is worth knowing when
   grepping.

   ** A degeneracy this does NOT rule out

   Axiom-freedom of the general adjunction is compatible with the free
   algebra being a single `≈`-class: for an [E] whose laws identify
   everything, [Free_Variety E X] is the one-point algebra and the
   adjunction still holds, axiom-free.  Nothing here excludes that, and
   nothing should — it is the correct answer for such an [E].  What rules
   it out at a PARTICULAR presentation is a separation result, and the
   one shipped is Test/ProbeVarietyFree441.v's [free_comm_not_collapsed]
   for the commutative magma.  No general non-collapse statement is made.

   ** Not delivered

   No [Free_Variety : Variety E] for #440's Leibniz variety.  Note the
   corrected reason: not "impossible" — it exists whenever the
   presentation has a computable normal form, and the free commutative
   magma was built that way to refute the earlier claim — but not
   uniformly in ⟨Ω,E⟩, which is what this file delivers.  The
   normal-form construction for that one presentation is about 250 lines
   concerning a single signature and is not shipped.  No
   Birkhoff HSP theorem: the non-example below is stated over a FIXED
   signature and rules out every [EqSignature RingOp] whose models are
   exactly the fields, which is what Mac Lane's remark needs and no more.
   No cardinality bound.  An earlier revision continued "and no solution
   set, hence no GAFT route"; since #450 both are in tree
   (Instance/Variety/Colimit.v's [SVariety_Forget_solution_set] and
   [Free_Variety_via_GAFT], "Why not GAFT" above), and the bound is
   still not stated because the congruence index makes it unnecessary.
   No functor [Variety E ⟶ SVariety E]: [leibniz_soa] is an object map only,
   so #440's category and this one are not related as categories here.
   No
   free ring, free abelian group or free module as named instances —
   those need their signatures spelled out, and the two shipped instances
   (the commutative magma and the group) are what the issue's own
   Verification block asks to run. *)

