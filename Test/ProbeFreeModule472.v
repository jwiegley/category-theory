Example p472_c75_ZM_obj (X : Sets) :
  fobj[FreeAbF] X = Ab_Forget (FreeAbObject X) := eq_refl.

(* C76: ...whose carrier is the formal sums. *)
Example p472_c76_ZM_carrier (X : Sets) : carrier (fobj[FreeAbF] X) = FATerm X
  := eq_refl.

(* C77: η_X is the insertion... *)
Example p472_c77_ZM_ret (X : Sets) : @ret _ _ FreeAbMonad X = free_ab_insert X
  := eq_refl.

(* C78: ...x ↦ ⟨x⟩... *)
Example p472_c78_ZM_ret_fun (X : Sets) (x : carrier X) :
  @ret _ _ FreeAbMonad X x = fa_gen x := eq_refl.

(* C79: ...μ = U ε F... *)
Example p472_c79_ZM_join_counit (X : Sets) :
  @join _ _ FreeAbMonad X
    = fmap[Ab_Forget] (@counit _ _ _ _ free_ab_adjunction_hom (FreeAb X))
  := eq_refl.

(* C80: ...μ⟨t⟩ = t... *)
Example p472_c80_ZM_join_gen (X : Sets) (t : FATerm X) :
  @join _ _ FreeAbMonad X (@fa_gen (Ab_Forget (FreeAbObject X)) t) = t
  := eq_refl.

(* C81: ...μ is the fold of the identity... *)
Example p472_c81_ZM_join_fun (X : Sets)
  (k : FATerm (Ab_Forget (FreeAbObject X))) :
  @join _ _ FreeAbMonad X k
    = fa_eval (A := FreeAbObject X) (@id Sets (Ab_Forget (FreeAbObject X))) k
  := eq_refl.

(* C82: ...and μ 0 = 0. *)
Example p472_c82_ZM_join_zero (X : Sets) :
  @join _ _ FreeAbMonad X fa_zero = fa_zero := eq_refl.

(* C83: ℤ[u] is the relabelling up to ≈. *)
Definition p472_c83_ZM_map_equiv {X Y : Sets} (u : X ~{Sets}~> Y)
  (t : FATerm X) : fmap[FreeAbF] u t ≈ fa_relabel u t := ZM_map_equiv u t.

(* R26 *)
