(* C84: the leg [to] of [Ab_EM_iso] is K... *)
Example p472_c84_ab_iso_to : to Ab_EM_iso = EM_Comparison free_ab_adjunction_hom
  := eq_refl.

(* C85: ...and the leg [from] is [EM_to_AbS]. *)
Example p472_c85_ab_iso_from : from Ab_EM_iso = EM_to_AbS := eq_refl.

(* C86: K G has carrier G... *)
Example p472_c86_ab_K_carrier (G : Ab) : `1 (fobj[Ab_K] G) = Ab_Forget G
  := eq_refl.

(* C87: ...K f is f... *)
Example p472_c87_ab_K_map {G H : Ab} (f : G ~{Ab}~> H) :
  t_alg_hom[fmap[Ab_K] f] = fmap[Ab_Forget] f := eq_refl.

(* C88: ...its structure map is U ε_G... *)
Example p472_c88_ab_K_alg (G : Ab) :
  t_alg[`2 (fobj[Ab_K] G)]
    = fmap[Ab_Forget] (@counit _ _ _ _ free_ab_adjunction_hom G) := eq_refl.

(* C89: ...the evaluation of a formal sum to its actual sum... *)
Example p472_c89_ab_K_alg_fun (G : Ab) (t : FATerm (Ab_Forget G)) :
  t_alg[`2 (fobj[Ab_K] G)] t = fa_eval (@id Sets (Ab_Forget G)) t
  := eq_refl.

(* C90: ...so ⟨x⟩ ↦ x... *)
Example p472_c90_ab_K_alg_gen (G : Ab) (x : carrier (Ab_Forget G)) :
  t_alg[`2 (fobj[Ab_K] G)] (fa_gen x) = x := eq_refl.

(* C91: ...0 ↦ 0... *)
Example p472_c91_ab_K_alg_zero (G : Ab) :
  t_alg[`2 (fobj[Ab_K] G)] fa_zero = cmon_zero G := eq_refl.

(* C92: ...⟨x⟩ + ⟨y⟩ ↦ x + y... *)
Example p472_c92_ab_K_alg_plus (G : Ab) (x y : carrier (Ab_Forget G)) :
  t_alg[`2 (fobj[Ab_K] G)] (fa_plus (fa_gen x) (fa_gen y))
    = cmon_plus G x y := eq_refl.

(* C93: ...and −⟨x⟩ ↦ −x. *)
Example p472_c93_ab_K_alg_neg (G : Ab) (x : carrier (Ab_Forget G)) :
  t_alg[`2 (fobj[Ab_K] G)] (fa_neg (fa_gen x)) = ab_neg G x := eq_refl.

(* C94: the group of an algebra has its carrier... *)
Example p472_c94_ab_EM_carrier (x : ZMAlg) :
  cmon_setoid (fobj[EM_to_AbS] x) = `1 x := eq_refl.

(* C95: ...0 = ev⟨⟩... *)
Example p472_c95_ab_EM_zero (x : ZMAlg) :
  cmon_zero (fobj[EM_to_AbS] x) = t_alg[`2 x] fa_zero := eq_refl.

(* C96: ...a + b = ev(⟨a⟩ + ⟨b⟩)... *)
Example p472_c96_ab_EM_plus (x : ZMAlg) (a b : `1 x) :
  cmon_plus (fobj[EM_to_AbS] x) a b
    = t_alg[`2 x] (fa_plus (fa_gen a) (fa_gen b)) := eq_refl.

(* C97: ...−a = ev(−⟨a⟩)... *)
Example p472_c97_ab_EM_neg (x : ZMAlg) (a : `1 x) :
  ab_neg (fobj[EM_to_AbS] x) a = t_alg[`2 x] (fa_neg (fa_gen a)) := eq_refl.

(* C98: ...and an algebra map is its own homomorphism. *)
Example p472_c98_ab_EM_map {x y : ZMAlg} (f : x ~{ZMAlg}~> y) :
  cmon_map (fmap[EM_to_AbS] f) = t_alg_hom[f] := eq_refl.

(* C99: its [Prop] equality compares one-generator sums. *)
Example p472_c99_ab_EM_prop (x : ZMAlg) (a b : `1 x) :
  @pequiv _ _ (cmon_prop (fobj[EM_to_AbS] x)) a b
    = @fa_eq (`1 x) (fa_gen a) (fa_gen b) := eq_refl.

(* C100: the group round trip keeps the carrier... *)
