  - exact (uenv_extend A h).
  - intro v; simpl; reflexivity.
  - intros g Hg t; simpl.
    symmetry.
    apply (uenv_extend_unique A h (`1 g)).
    + intro a; exact (uenv_alg_hom_scal A g a).
    + intro v; symmetry; exact (Hg v).
Defined.

