  refine (uq_trans (uq_mul (uenv_refl s) _)
            (uq_sym (uq_add_zero_r (uen_mul s UZ)))).
  refine (uq_trans (uq_sym (uq_scal_add (rig_zero (`1 K))
                              (rig_zero (`1 K)))) _).
  exact (uq_scal (rig_add_zero_l (`1 K) (rig_zero (`1 K)))).
Qed.

