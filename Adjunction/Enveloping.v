(** * The universal enveloping algebra, and E ⊣ V

    Book: Mac Lane, "Categories for the Working Mathematician", 2nd ed.,
          GTM 5, §IV.2, printed p. 89 (PDF p. 98), Exercise 3
          (maclane:IV.2:ex3).  With Lie_K the category of small Lie
          algebras over K and V : Alg_K ⟶ Lie_K the functor putting the
          commutator bracket [a,b] = ab - ba on an associative algebra,
          the exercise asks that the universal enveloping algebra
          functor E be exhibited as a left adjoint of V.
    nLab:      https://ncatlab.org/nlab/show/universal+enveloping+algebra
    nLab:      https://ncatlab.org/nlab/show/Poincare-Birkhoff-Witt+theorem
    Wikipedia: https://en.wikipedia.org/wiki/Universal_enveloping_algebra

    THIS FILE IS E AND THE ADJUNCTION, work items 3 and 4 of the issue,
    and nothing else.  Items 1 and 2 -- the two categories and the
    commutator functor V -- are Instance/Rng/Algebras/Associative.v and
    Instance/Lie.v, both of which are CONSUMED here and neither of which
    is modified: [AAlgObject], [AAlg], [AAlgHom], [AAlg_RMod],
    [aalg_central], [UT2_AAlg] come from the first, and [LieObject],
    [LieHom], [Lie], [lie_of_aalg], [CommutatorFunctor], [lie_abelian]
