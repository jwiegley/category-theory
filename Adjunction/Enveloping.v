Lemma uenv_universal (L : Lie K) (A : AAlg K)
  (h : L ~{Lie K}~> fobj[CommutatorFunctor K] A) :
  ∃! g : UEnvAlg L ~{AAlg K}~> A,
    h ≈ fmap[CommutatorFunctor K] g ∘ uenv_insert L.
