    ** POINCARÉ-BIRKHOFF-WITT: DEFERRED, AND NOTHING BELOW DEPENDS ON IT

    The issue's reviewer check is that the adjunction be proved WITHOUT
    appealing to PBW.  It is, and the reason is structural rather than a
    matter of care: an adjunction is a statement about a universal
    property, and the universal property here is proved by ONE induction
    over the term type ([uenv_extend_unique], five cases) and ONE
    induction over the generating congruence ([uenv_eval_respects],
    twenty-two cases).  Neither mentions a basis, a filtration, a
    grading, an ordering of generators, or a symmetric algebra, and the
    strings "basis", "filtration" and "PBW" occur nowhere below this
    essay.

    PBW IS NOT PROVED AND IS NOT ASSUMED.  What it would give, and what
    is therefore NOT claimed anywhere in this file: that [uenv_insert]
    is injective; that L embeds in U(L); that [EnvelopingFunctor] is
    faithful; that U(L) of an abelian Lie algebra is a polynomial
    algebra.  In particular [uenv_ut2_gens_distinct] is NOT an instance
    of PBW -- it separates two SPECIFIC generators of ONE Lie algebra by
    mapping OUT into [UT2], and says nothing about any other L, nor
    about any other pair of elements.

